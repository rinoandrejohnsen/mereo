# A CONDITION is an ordinary value expression read with three prose operator
# A CONDITION IS WRITTEN IN OPERATORS, never in words: `==`, `!=`, `&&`, `||`.
# The words `is`, `and` and `or` used to be accepted here and mean exactly those,
# which read well -- but it made a condition indistinguishable from an
# assignment, and that is now load-bearing. `GUARD goes` opens a conditional
# scope, so the parser has to decide what `x is 2 goes` is; with the words gone,
# a line containing `is` outside a condition site is an assignment and nothing
# else. The words stay in their own constructs (`X is EXPR`, `with A and B`, the
# cascade's `or`), where no condition can appear.
_COND_WORD = {"is": "==", "and": "&&", "or": "||"}


def _top_level_logic_ops(cond):
    """[(index, op)] for each top-level `&&`/`||` in a condition -- skipping any
    inside parentheses or a string literal. The operator twin of
    `_top_level_cond_ops`, which still reads WORDS because the value cascade
    separates its clauses with the word `or` and that is not a condition."""
    out, depth, i, inq = [], 0, 0, False
    while i < len(cond):
        c = cond[i]
        if c == '"':
            inq = not inq
        elif not inq:
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif depth == 0 and cond[i:i + 2] in ("&&", "||"):
                out.append((i, cond[i:i + 2]))
                i += 2
                continue
        i += 1
    return out


def _top_level_cond_ops(cond):
    """[(index, word)] for each top-level `and`/`or` in a condition -- skipping
    any inside parentheses or a string literal."""
    out, depth, i, inq = [], 0, 0, False
    while i < len(cond):
        c = cond[i]
        if c == '"':
            inq = not inq
        elif not inq:
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif depth == 0 and (i == 0 or not (cond[i - 1].isalnum()
                                                or cond[i - 1] == "_")):
                m = re.match(r"(and|or)(?![\w])", cond[i:])
                if m:
                    out.append((i, m.group(1)))
                    i += len(m.group(1))
                    continue
        i += 1
    return out


def guarded_scope(s, n):
    """`GUARD goes` -- an anonymous scope with an ENTRY CONDITION, which is how
    mereo says `if`. It is tried after `NAME goes`, so a single identifier still
    opens a NAMED scope and a guard therefore has to carry a comparison
    (`z != 0 goes`, never `z goes`).

    This is why a condition is spelled in operators: `x is 2 goes` would be
    indistinguishable from the assignment `x is "2 goes"`, and the assignment
    rule would swallow it silently. With `is` gone from conditions, a line
    ending in ` goes` is a scope opener and nothing else."""
    m = re.match(r"^(.+) goes$", s)
    if not m or re.fullmatch(r"\w+", m.group(1)):
        return None
    guard = m.group(1).strip()
    if re.fullmatch(r"\w+ likely", guard):
        return None              # `LABEL likely goes` -- a crossroad, not a guard
    if re.search(r"\bwhen\b", guard):
        fail(f"line {n}: `{s}` -- a conditional scope is `GUARD goes`, with no "
             "`when`. `LABEL when GUARD goes` is a crossroad ROAD, and a road "
             "may only follow its `LABEL likely goes` crossroad.")
    return {"type": "scope_start", "cond": guard, "line": n}


def split_conjuncts(cond):
    """A condition -> its top-level AND-clauses. `A && B` splits (checking B
    only after A held is exactly what `&&` means), so a fallible `ensure` can
    give each conjunct its own failure record naming the value that actually
    failed. A top-level `||` does NOT split: it is one predicate, and when it
    fails EVERY disjunct is false, so reporting the first subject is honest."""
    ops = _top_level_logic_ops(cond)
    if not ops or any(w == "||" for _, w in ops):
        return [cond.strip()]
    parts, prev = [], 0
    for pos, _ in ops:
        parts.append(cond[prev:pos].strip())
        prev = pos + 2
    parts.append(cond[prev:].strip())
    return [p for p in parts if p]


def render_choice_cond(cond, scalars, buffers, ln):
    """A condition -> a C predicate, via the shared expression grammar (so `is`,
    `and`, `or`, comparisons, arithmetic and parens all work, and either side
    may be any value -- inlining can substitute a constant for a parameter, as
    in `x > 5` becoming `10 > 5`)."""
    return resolve_value(cond.strip(), scalars, buffers, ln, cond=True)


# One forced conditional move for a cascade clause (under MEREO_CMOV): compute
# the condition into a register, then `cmovne` the value into X on non-zero --
# a guaranteed cmov whatever GCC's cost model would have done with the ternary.
_CMOV_TMPL = ('{{ long _cc = ({cond}); __asm__ ('
              '"test %[c],%[c]\\n\\tcmovne %[v],%[x]" '
              ': [x] "+r" ({x}) : [c] "r" (_cc), [v] "r" ((long)({val})) '
              ': "cc"); }}')


def render_cond(cond, scalars, buffers, ln):
    """A loop/back-edge condition -> a C predicate. The same shared grammar as
    every other condition site (see `render_choice_cond`); a bare scalar is a
    truthiness test."""
    return render_choice_cond(cond, scalars, buffers, ln)



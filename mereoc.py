def _unparen(c):
    """A generated C fragment with its redundant outer parens stripped."""
    c = c.strip()
    while c.startswith("("):
        depth, end = 0, -1          # -1: an unbalanced fragment is left alone
        for i, ch in enumerate(c):
            depth += (ch in "([") - (ch in ")]")
            if depth == 0:
                end = i
                break
        if end != len(c) - 1:
            break
        c = c[1:-1].strip()
    return c


def _lead_binop(c):
    """(left, op, rest) at the FIRST depth-0 binary operator of a generated C
    fragment, else None. The emitter always spaces a binary operator (it builds
    `(L op R)`) and never a unary one (`(-x)`, `(~x)`), so ` op ` marks one
    unambiguously."""
    depth = 0
    for i, ch in enumerate(c):
        depth += (ch in "([") - (ch in ")]")
        if depth == 0 and ch == " ":
            m = _C_BINOP.match(c, i)
            if m:
                return c[:i], m.group(1), c[m.end():]
    return None


def deref_addr(addr_c):
    """An address about to be dereferenced, handed to C as POINTER arithmetic
    instead of an integer round-trip. A buffer name resolves to `(long)NAME`
    because every mereo value is a long -- but `*(long *)((long)b + 8)` launders
    the address through an integer, and GCC's points-to analysis gives up on a
    laundered address: no SROA, so a block that could have stayed in registers
    gets a real stack frame. `NAME` is a C array, so `NAME + 8` is the very same
    address with the array still in view, and the load is free again.

    Only the leftmost term of an additive chain is unwrapped -- left
    associativity makes that the base -- so the result is one pointer plus longs.
    Any other operator (a multiply, a nested load, a scalar base) keeps the cast:
    that address really is an integer and the C should say so. The rewrite needs
    the base to be exactly `(long)NAME`, so a fragment this misreads (a string
    literal holding ` + `) simply fails to rewrite -- it cannot rewrite wrongly.
    An unchanged address comes back verbatim, so a program this does not touch
    emits byte-identical C; a rewritten one is parenthesized as a whole, ready to
    splice into the `*(T *)(...)` every caller wraps it in."""
    inner = _unparen(addr_c)
    bare = _LAUNDERED.match(inner)
    if bare:
        return bare.group(1)
    split = _lead_binop(inner)
    if split is None or split[1] not in ("+", "-"):
        return addr_c
    left, op, rest = split
    base = deref_addr(left)
    return f"({base} {op} {rest})" if base != left else addr_c


def load_c(addr_c, width, signed, big, ln, kind="", vol=False):
    """C expr reading `width` bytes at addr_c under a view. `float` reads IEEE-754
    (4 bytes single, 8 bytes double); big-endian byte-swaps; the sign picks the
    cast that sign- or zero-extends to a long; `volatile` marks the access so the
    compiler cannot elide, cache, or reorder it (MMIO / shared memory)."""
    addr_c = deref_addr(addr_c)
    v = "volatile " if vol else ""
    if kind == "float":
        ftype = {"4": "float", "8": "double"}.get(str(width))
        if ftype is None:
            fail(f"line {ln}: a `float` view needs a 4- or 8-byte backing, "
                 f"not {width}")
        return f"(*({v}{ftype} *)({addr_c}))"
    if kind == "whole":
        fail(f"line {ln}: `as whole` converts a value to an integer -- it is "
             "not a memory-load view")
    if str(width) not in ("1", "2", "4", "8"):
        fail(f"line {ln}: memory width must be 1, 2, 4, or 8 bytes, "
             f"not '{width}'")
    w = int(width)
    if big and w > 1:
        return big_read(addr_c, w, signed, ln, vol)
    return f"(*({v}{width_type(str(w), ln, signed)} *)({addr_c}))"


# memory ordering for the atomic ops; the default (no word) is the safe, strong
# sequential consistency. On x86-64 acquire/release are free (TSO); relaxed drops
# the compiler barrier; seq_cst stores/RMW take a `lock`/`mfence`.
_ATOMIC_ORDER = {"": "__ATOMIC_SEQ_CST", "relaxed": "__ATOMIC_RELAXED",
                 "acquire": "__ATOMIC_ACQUIRE", "release": "__ATOMIC_RELEASE"}


def atomic_c(op, order, size, addr_c, args, ln):
    """The GCC `__atomic_*` builtin for one atomic op on `size` bytes at addr_c.
    load/add/compare are expressions (a value); store is a void statement. These
    lower to `lock`-prefixed instructions / the right fence for the ordering."""
    t = width_type(str(size), ln)            # unsigned N-byte integer type
    p = f"({t} *)({deref_addr(addr_c)})"
    o = _ATOMIC_ORDER[order]
    if op == "load":
        return f"__atomic_load_n({p}, {o})"
    if op == "store":
        return f"__atomic_store_n({p}, ({t})({args[0]}), {o})"
    if op == "add":
        return f"__atomic_fetch_add({p}, ({t})({args[0]}), {o})"
    if op == "compare":                      # CAS -> 1 if it swapped, else 0
        return (f"({{ {t} _e = ({t})({args[0]}); "
                f"__atomic_compare_exchange_n({p}, &_e, ({t})({args[1]}), 0, "
                f"{o}, {o}); }})")
    fail(f"line {ln}: unknown atomic op '{op}'")


def layout_field_c(actual, buffers, ln):
    """`INST.FIELD` where INST is a layout block -> the field's memory cell
    (rvalue here, lvalue via the store path); a big-endian field byte-swaps on
    read. None if `actual` is not a layout field access."""
    m = re.match(r"^(\w+)\.(\w+)$", actual)
    if not m or m.group(1) not in buffers or not buffers[m.group(1)].get("playout"):
        return None
    inst, field = m.group(1), m.group(2)
    pl = buffers[inst]["playout"]
    if field not in pl:
        fail(f"line {ln}: layout '{inst}' has no field '{field}' "
             f"(has: {', '.join(pl)})")
    off, width, signed, big = pl[field]
    rl = buffers[inst].get("reglens")
    if rl:                                 # the backing is a register word: the
        word, base = rl                    # field is a slice of it, not a cell
        return (register_read(word, base + off, width, signed, big, ln),
                off, width, signed, big)
    base = buffers[inst].get("addr", f"(long){inst}")   # a lens -> its backing
    addr = f"({base} + {off})"
    cexpr = load_c(addr, width, signed, big, ln)        # the field's baked view
    return (cexpr, off, width, signed, big)


def container_field_c(actual, buffers, ln):
    """`C.FIELD` where C is a `container of N bytes`: `data` (the byte
    region's address) or `count` (its mutable content-length scalar). Its total
    size is `C.size`, not a container field. None if not a container access."""
    m = re.match(r"^(\w+)\.(data|count)$", actual)
    if not m or not buffers.get(m.group(1), {}).get("container"):
        return None
    c, field = m.group(1), m.group(2)
    if field == "data":
        return f"(long){c}"
    return f"{c}_{field}"                # count -> C_count


def publish_state(slot, defn):
    """Expose an instance's state so `INSTANCE.FIELD` can read it. Only the
    single-word paths: a composed part's state is reached through the part."""
    for path in defn.get("flat", ()):
        if re.fullmatch(r"\w+", path):
            INSTANCE_FIELDS[(slot["name"], path)] = state_cell(
                slot["name"], path, defn, slot.get("backing"))


def is_pure_layout(defn):
    """Is this definition DATA, laid out in a block? A layout stays data even
    when it carries templates -- a template is inlined work, not a lifecycle, so
    it must not cost the instance its packed representation (a flag view's whole
    point is the word you hand to a syscall). Only real ownership -- state,
    parts, bases, an `acquire`/`release` -- makes an instance a resource."""
    return kind_of(defn) == "layout"


def kind_of(defn):
    """The word for what a definition IS, so an error names it the way the docs
    do: a RESOURCE owns one thing (state, bases, or an acquire/release); a
    LAYOUT is fields you lay over bytes with `as`; a TEMPLATE GROUP interprets
    nothing and owns nothing -- it is only reusable work. Anything we cannot
    place (an unknown name, a half-parsed block) is just a `definition`."""
    if defn.get("free"):                 # one template, no group around it
        return "template"
    if (defn.get("layered") or defn.get("bases") or defn.get("state")
            or defn.get("parts")
            or any(m.get("role") in ("acquire", "release")
                   for m in (defn.get("methods") or {}).values())):
        return "resource"
    if defn.get("packed") or defn.get("bitdecl"):
        return "layout"
    if defn.get("methods"):
        return "template group"
    return "definition"


def is_resource(defn):
    """Is this definition a RESOURCE or plain DATA? A resource has a lifecycle -- any
    method of its own, or one inherited as a layer from its bases -- so its state
    is register-resident (`INST_field` longs, keeping an fd in a register across
    syscalls) and it earns a tower floor. This asks only whether a LIFECYCLE
    exists. Whether an instance is DATA -- a contiguous, addressable block -- is
    `is_pure_layout`, because a layout carrying templates has methods and yet
    owns nothing. A site picking a REPRESENTATION must ask there: the two
    disagreed once, and the emitter declared a block while accesses used
    scalars."""
    return bool(defn["methods"]) or bool(defn.get("layered"))



def state_cell(inst_name, path, defn, backing=None):
    """The C lvalue for one field of an instance. Representation follows the
    shape (same `N bytes` syntax either way): a PURE LAYOUT (byte fields, no
    lifecycle) is a contiguous block, so a field is a memory cell; a resource
    (an `acquire`/`release`, or scalar state) keeps each field in a register-
    resident `INST_field` long -- so a fd stays in a register across syscalls."""
    pl = defn.get("playout")
    if backing is not None and pl is not None and path in pl:
        # a behavioral lens: the field lives in the provided backing's bytes,
        # not in an auto-allocated scalar (the fd is memory-resident here).
        off, width, signed, _big = pl[path]
        return (f"(*({width_type(str(width), 0, signed)} *)"
                f"({deref_addr(f'{backing} + {off}')}))")
    if pl is not None and is_pure_layout(defn) and path in pl:
        off, width, signed, _big = pl[path]
        return (f"(*({width_type(str(width), 0, signed)} *)"
                f"({deref_addr(f'(long){inst_name} + {off}')}))")
    if path in defn.get("arrays", ()):        # a resource's in-instance buffer:
        return f"(long){inst_name}_{path.replace(' ', '_')}"   # its name IS its addr
    return f"{inst_name}_{path.replace(' ', '_')}"


def flag_field_c(actual, buffers, ln):
    """`INST.FIELD` where INST is a flag view -> (read_expr, cell, ubyte,
    lo, mask, cast), where `cell` is the lvalue holding the word and `cast` is
    the type a store must come back through (empty unless the word is a signed
    scalar). Reading a bit field is `(cell >> lo) & mask`. A flag view lensed
    over a register backing is the same shape with the word itself as the cell,
    and the view's byte offset folded into the shift. None if not a flag field."""
    m = re.match(r"^(\w+)\.(\w+)$", actual)
    if (not m or m.group(1) not in buffers
            or not buffers[m.group(1)].get("bitfields")):
        return None
    inst, field = m.group(1), m.group(2)
    bf = buffers[inst]["bitfields"]
    if field not in bf:
        fail(f"line {ln}: flag view '{inst}' has no bit '{field}' "
             f"(has: {', '.join(bf)})")
    lo, nbits = bf[field]
    mask = (1 << nbits) - 1
    rl = buffers[inst].get("reglens")
    if rl:                                 # the bits live in a register word
        word, off = rl
        return (f"(({_word_bits(word)} >> {lo + off * 8}) & {mask})", word,
                "unsigned long", lo + off * 8, mask,
                "" if word in REGISTER_WORDS else "long")
    ut = _UBYTE[buffers[inst]["bitwidth"]]
    base = deref_addr(buffers[inst].get("addr", f"(long){inst}"))
    cell = f"*({ut} *)({base})"
    read = f"((({cell}) >> {lo}) & {mask})"
    return (read, cell, ut, lo, mask, "")


def size_of_c(actual, scalars, buffers, ln):
    """`X.size` -> X's byte size as a compile-time integer constant: a
    string/`bytes` literal's length, a buffer or container's size, or a view
    instance's extent (`sizeof`). None (so `parse_expr` can tokenize it) unless
    it's a standalone `<literal>.size` or `<name-in-buffers>.size`; a scalar has
    no byte size and errors in the tokenizer.

    `.size` is the one member that is not a declared field: the compiler answers
    it for anything with bytes, so a layout view may not declare a field of that
    name (refused where fields are elaborated)."""
    m = re.match(r"^(.+)\.size$", actual.strip())
    if not m:
        return None
    target = m.group(1).strip()
    if is_str(target):
        return str(len(parse_bytes_literal(target, ln)))
    if re.fullmatch(r"\w+", target) and target in buffers:
        sz = buffers[target].get("size")
        if sz is not None and str(sz).isdigit():
            return str(sz)
    return None


def resolve_value(actual, scalars, buffers, ln, cond=False):
    actual = actual.strip()
    if is_str(actual):                   # a whole string literal
        return lit_c(actual)
    so = size_of_c(actual, scalars, buffers, ln)   # `X.size` -> const bytes
    if so is not None:
        return so
    ff = flag_field_c(actual, buffers, ln)     # `BIT of flag-view`
    if ff is not None:
        return ff[0]
    sf = layout_field_c(actual, buffers, ln)   # `layout-INST.FIELD`
    if sf is not None:
        return sf[0]
    cf = container_field_c(actual, buffers, ln)   # `container.FIELD`
    if cf is not None:
        return cf
    inf = instance_field_c(actual, ln)   # `INSTANCE.FIELD` -- resource state
    if inf is not None:
        return inf
    va = view_access_c(actual, ln, scalars, buffers)   # `RESOURCE.FIELD [+ N]`
    if va is not None:
        return va
    return parse_expr(actual, scalars, buffers, ln, cond)


# math is symbolic and lowers straight to C. A full expression with C precedence
# and parentheses: atoms are numbers, scalars (as-is), buffers (their address),
# `[ADDR : N]` loads (N in 1/2/4/8), `(...)`, and unary `~` / `-`; binary ops are
#   arithmetic  + - * / %      bitwise  & | ^      shifts  << >>
#   compare     < > <= >= == != (yields 0/1)       logical  && ||
# so long expressions no longer need one-operation-per-step temporaries.
_FLOATLIT = r"\d[\d_]*\.\d[\d_]*(?:[eE][-+]?\d[\d_]*)?"
_TOK_RE = re.compile(
    r'\s*(' + _FLOATLIT + r'|0[xX][0-9a-fA-F_]+|0[bB][01_]+|\d[\d_]*|'
    r'"(?:[^"\\]|\\.)*"\.\w+|[A-Za-z_]\w*\.\w+|[A-Za-z_]\w*|'
    r'<<|>>|<=|>=|==|!=|&&|\|\||'
    r'"(?:[^"\\]|\\.)*"|[-+*/%&|^~<>()\[\]:])')
_BINPREC = {"||": 1, "&&": 2, "|": 3, "^": 4, "&": 5,
            "==": 6, "!=": 6, "<": 7, ">": 7, "<=": 7, ">=": 7,
            "<<": 8, ">>": 8, "+": 9, "-": 9, "*": 10, "/": 10, "%": 10}


def _tokenize_expr(s, ln):
    toks, i = [], 0
    while i < len(s):
        m = _TOK_RE.match(s, i)
        if not m:
            if s[i:].strip() == "":
                break
            fail(f"line {ln}: cannot read expression near '{s[i:].strip()}'")
        toks.append(m.group(1))
        i = m.end()
    return toks


def parse_expr(actual, scalars, buffers, ln, cond=False):
    """A mereo value expression -> a C expression string (precedence-climbing).
    With `cond`, the three prose operator words are read as their C operators
    (`is`->`==`, `and`->`&&`, `or`->`||`) -- see `render_choice_cond`. A string
    literal tokenizes whole, so `and` inside one is never touched."""
    if is_int(actual):
        return lit_c(actual)                 # bare -1 / 0xNN verbatim
    toks = _tokenize_expr(actual, ln)
    if cond:
        for t in toks:
            if t in _COND_WORD:
                fail(f"line {ln}: `{t}` is not a condition operator -- write "
                     f"`{_COND_WORD[t]}`. A condition is spelled in operators "
                     "(`==`, `!=`, `&&`, `||`) so that it can never be read as "
                     "an assignment: `x == 2 goes` opens a conditional scope, "
                     "and `x is 2` sets x. The words keep their own jobs "
                     "elsewhere -- `X is EXPR`, `with A and B`, and the `or` "
                     "between cascade clauses.")
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        t = toks[pos[0]]; pos[0] += 1
        return t

    def cast_suffix(val):
        """A value may carry a trailing cast: `EXPR as VIEW` REINTERPRETS the bits
        (they never change) -- `as unsigned` reads them unsigned, `as float`
        reads the 64 bits as a double (a bit-cast). `EXPR to TARGET` CONVERTS,
        actually changing the value: `to float` (int -> double), `to whole`
        (double -> int, truncating). Byte order (`big`/`little`) is a memory
        property, so it is rejected on a register value."""
        op = peek()
        if op not in ("as", "to"):
            return val
        take()
        words = []
        while peek() in VIEW_WORDS:
            words.append(take())
        if op == "to":                   # a CONVERSION -- changes the value
            if words == ["float"]:
                return f"((double)({val}))"
            if words == ["whole"]:
                return f"((long)({val}))"
            fail(f"line {ln}: `to` converts to `float` or `whole`, not "
                 f"'{' '.join(words) or '(nothing)'}'")
        signed, big, kind, vol = view_flags(words, ln)   # `as` -- a reinterpret
        if vol:
            fail(f"line {ln}: `as volatile` qualifies a memory ACCESS; put it on "
                 "a `[addr:N]` read/write, not a register value")
        if kind == "float":              # the same 64 bits, read as a double
            return (f"({{ union {{ long _l; double _d; }} _u; "
                    f"_u._l = (long)({val}); _u._d; }})")
        if kind == "whole":
            fail(f"line {ln}: `as whole` would change the value; use `to whole` "
                 "to convert a float to an integer")
        if big:
            fail(f"line {ln}: `as big`/`little` is a byte-order view for a "
                 "`[addr:N]` memory load; a register value has no byte order "
                 "(use `as signed`/`as unsigned` to reinterpret its sign)")
        return f"((long){val})" if signed else f"((unsigned long){val})"

    def atom():
        t = peek()
        if t is None:
            fail(f"line {ln}: unexpected end of expression '{actual}'")
        take()
        if t == "(":
            e = climb(0)
            if take() != ")":
                fail(f"line {ln}: missing ')' in '{actual}'")
            return cast_suffix(e)
        if t == "[":
            reg = peek() if peek() in REGISTER_WORDS else None
            addr = None if reg else climb(0)
            if reg:
                take()                       # the word's name, then `+ CONST`
                off = []
                while peek() not in (":", "]", None):
                    off.append(take())
                if off and off[0] == "+":
                    off = off[1:]
                off = register_offset(reg, " ".join(off), ln)
            width = "1"
            if peek() == ":":
                take(); width = take()
            if take() != "]":
                fail(f"line {ln}: missing ']' in '{actual}'")
            signed, big, kind, vol = False, False, "", False   # default: uns. LE
            if peek() == "as":
                take()
                words = []
                while peek() in VIEW_WORDS:
                    words.append(take())
                signed, big, kind, vol = view_flags(words, ln)
            if reg:
                if kind or vol:
                    why = ("a float view reinterprets BYTES, and a register word "
                           "has none" if kind else
                           "volatile orders a MEMORY access, and a register word "
                           "is not memory")
                    fail(f"line {ln}: `as {kind or 'volatile'}` on "
                         f"`[{reg} ...]` -- '{reg}' is `in register`: {why}")
                if str(width) not in ("1", "2", "4", "8"):
                    fail(f"line {ln}: memory width must be 1, 2, 4, or 8 bytes, "
                         f"not '{width}'")
                return cast_suffix(register_read(reg, off, int(width), signed,
                                                 big, ln))
            # the load itself is a memory-view reinterpret; a trailing `to`
            # (convert) then applies to the loaded value, e.g. `[b:8] to whole`
            return cast_suffix(load_c(addr, width, signed, big, ln, kind, vol))
        if t == "~":
            return f"(~{atom()})"
        if t == "-":
            return f"(-{atom()})"
        _mem = re.fullmatch(r'((?:"(?:[^"\\]|\\.)*")|[A-Za-z_]\w*)\.(\w+)', t)
        if t[0] == '"' and not _mem:
            return lit_c(t)
        if t == "high":                      # a bit value: high = 1, low = 0
            return "1"
        if t == "low":
            return "0"
        if re.fullmatch(_FLOATLIT, t):       # a float literal -> a C double
            return cast_suffix(t.replace("_", ""))
        if is_int(t):
            return cast_suffix(norm_int_c(t))
        if _mem:                             # `INST.FIELD` -- a member access
            target, field = _mem.group(1), _mem.group(2)
            if field == "size":              # `X.size` -- compile-time bytes
                so = size_of_c(t, scalars, buffers, ln)
                if so is not None:
                    return cast_suffix(so)
                if target in scalars:
                    fail(f"line {ln}: `{t}` -- a scalar is a "
                         "register value with no byte size")
                if target in buffers:        # a buffer, but sized at RUNTIME
                    fail(f"line {ln}: `{t}` -- '{target}' is sized "
                         f"by a scalar, so its size is not known at compile "
                         f"time; use that scalar directly")
                fail(f"line {ln}: `{t}` -- '{target}' is not a "
                     "buffer, view, or literal")
            inst = target                    # a layout or flag field, usable
                                             # inside expressions (`(m.echo) & x`)
            ff = flag_field_c(t, buffers, ln)
            if ff is not None:
                return cast_suffix(ff[0])
            sf = layout_field_c(t, buffers, ln)
            if sf is not None:
                return cast_suffix(sf[0])
            cf = container_field_c(t, buffers, ln)
            if cf is not None:
                return cast_suffix(cf)
            inf = instance_field_c(t, ln)
            if inf is not None:
                return cast_suffix(inf)
            fail(f"line {ln}: '{t}' is not a flag or layout "
                 f"field in '{actual}'")
        if t in REGISTER_WORDS:
            # a backing's name IS its address, and this one has none. Its bytes
            # are still reachable -- through the slice, like any other backing.
            fail(f"line {ln}: '{t}' is `in register`, so it has no address -- and"
                 f" a backing's name IS its address. Read its bytes with "
                 f"`[{t} : {REGISTER_WORDS[t]}]`, or declare it `in stack` to "
                 f"hand it somewhere. (in '{actual}')")
        if t in buffers:
            return cast_suffix(buffers[t].get("addr", f"(long){t}"))  # lens->backing
        if t in scalars:
            return cast_suffix(t)
        fail(f"line {ln}: unknown name '{t}' in expression '{actual}'")

    def climb(rbp):
        left = atom()
        while True:
            op = peek()
            if op not in _BINPREC or _BINPREC[op] <= rbp:
                break
            take()
            left = f"({left} {op} {climb(_BINPREC[op])})"
        return left

    result = climb(0)
    if pos[0] != len(toks):
        fail(f"line {ln}: trailing tokens in expression '{actual}'")
    return result


# The label `repeat program` goes back to: the program's first step, emitted
# after the entry views and the signal dispositions so that neither is redone.
PROGRAM_AGAIN = "program_again"

INSTANCE_FIELDS = {}   # (instance, field) -> the C cell holding that state


def instance_field_c(actual, ln):
    """`INSTANCE.FIELD` where INSTANCE is a resource -> its state cell.
    A resource's state is PUBLIC: the resource is what holds the thing and what
    releases it, but naming a field is just a read -- mereo has no private."""
    m = re.match(r"^(\w+)\.(\w+)$", actual)
    if not m:
        return None
    inst, field = m.group(1), m.group(2)
    hit = INSTANCE_FIELDS.get((inst, field))
    if hit is None and any(i == inst for i, _ in INSTANCE_FIELDS):
        known = sorted(f for i, f in INSTANCE_FIELDS if i == inst)
        fail(f"line {ln}: '{inst}' has no state '{field}' "
             f"(has: {', '.join(known)})")
    return hit


def view_access_c(actual, ln, scalars=None, buffers=None):
    """`RESOURCE.FIELD [+ INDEX]` -> the field's C value. A scalar field reads
    directly (`count of arguments`); an indexed field takes `+ INDEX` and reads
    that element (`arguments.pointer + 1`). None if `actual` is not a field
    access. Only a resource named in `program with ...` is legal.

    INDEX was a literal (`\\d+`) until it needed not to be: with only a literal
    there is no loop over argv, so a program could read its first argument and
    nothing else -- which is why nothing in the corpus took more than one, and
    why there is no `getenv`. It is an ordinary expression now, resolved the
    same way any other index is."""
    m = re.match(r"^(\w+)\.(\w+)(?: \+ (.+))?$", actual)
    if not m:
        return None
    view, field, idx = m.group(1), m.group(2), m.group(3)
    if field == "size":                  # `X.size` -- the size-of operator,
        return None                      # not a resource field; let parse_expr run
    if view not in ENTRY_VIEWS:
        # not an entry view at all, so this is not the indexed form -- it is
        # ordinary arithmetic on a field read (`tag of h + 1`). Hand it back so
        # the expression path can tokenize it; claiming it here made every such
        # sum an error naming the entry views, which it has nothing to do with.
        return None
    if view not in VIEWS:
        extra = ("" if view in ENTRY_VIEWS else
                 f" ('{view}' is not one of {', '.join(ENTRY_VIEWS)})")
        fail(f"line {ln}: resource '{view}' is not declared -- add it to "
             f"`program with ...`{extra}")
    fields = VIEW_FIELDS[view]
    if field not in fields:
        fail(f"line {ln}: resource '{view}' has no field '{field}' "
             f"(has: {', '.join(fields)})")
    kind, cvar = fields[field]
    if kind == "scalar":
        if idx is not None:
            fail(f"line {ln}: field '{view}.{field}' takes no index")
        return cvar
    if idx is None:
        return f"(long){cvar}[0]"
    return f"(long){cvar}[{parse_expr(idx, scalars or {}, buffers or {}, ln)}]"



def wire_call(meth, defn, inst, conns_list, scalars, buffers, line):
    """Validate one attempt's bindings; -> valmap (method scope -> C expr)."""
    conns = {}
    for p, a, ln in conns_list:
        if p in conns:
            fail(f"line {ln}: parameter '{p}' connected twice")
        conns[p] = (a, ln)
    valmap = {}
    # iterate the params this CALL uses: a multi-step acquire shares one
    # `params` list across its calls, and each call touches only some of them
    # (for a single-call method every param is used, so this is the same set).
    for p in meth["dirs"]:
        if p not in conns:
            # an unconnected OUT port is DISCARDED: caught in the emitter's
            # shared `_sink` slot so the method's `ensure` still checks it (and
            # the record/graceful-shutdown paths still see the errno), but the
            # caller need not name a value it won't use. An unconnected value
            # (input) port stays an error -- inputs must be supplied.
            if meth["dirs"][p] == "return":
                valmap[p] = "_sink"
                scalars.setdefault("_sink", {"kind": "scalar", "name": "_sink",
                                             "init": "0", "line": 0})
                continue
            fail(f"line {line}: parameter '{p}' of '{meth['name']}' "
                 "is not connected")
        actual, ln = conns.pop(p)
        k = meth["dirs"][p]                     # value | return
        if k == "return":
            cf = container_field_c(actual, buffers, ln)
            if cf is not None:                  # `count of C` -> its scalar
                actual = cf                     # (data resolves to a non-scalar
            if actual not in scalars:           #  and fails below, not an output)
                fail(f"line {ln}: the result '{p}' must land in a scalar "
                     f"slot, got '{actual}'")
            valmap[p] = actual
        else:
            valmap[p] = resolve_value(actual, scalars, buffers, ln)
    for p, (_, ln) in conns.items():
        fail(f"line {ln}: '{meth['name']}' has no parameter '{p}'")
    for path in defn["flat"]:
        valmap[path] = state_cell(inst["name"], path, defn, inst.get("backing"))
    valmap.update(inst["borrowmap"])
    return valmap


def call_parts(meth, valmap):
    """-> (prim, syscall args, out expr, ensure clause predicates)."""
    prim = PRIMITIVES[meth["prim"]]
    args = []
    for k, port in prim["args"]:
        if k == "const":                     # a baked constant, not a call arg
            continue
        if port not in meth["bind"]:
            break
        actual, _ = meth["bind"][port]
        args.append(valmap.get(actual) or lit_c(actual))
    out = None
    if prim["out"] and prim["out"] in meth["bind"]:
        out = valmap[meth["bind"][prim["out"]][0]]
    ens = meth["ensure"]
    if not ens and prim.get("contract") and meth["role"] != "release":
        # No contract of its own -- inherit the syscall's. A method that writes
        # any `ensure` REPLACES it (it has taken responsibility), and a release
        # never gets one: a failed release cannot reroute.
        port, cmp_, val, ln = prim["contract"]
        if port in meth["bind"]:
            ens = [(meth["bind"][port][0], cmp_, val, ln)]
    clauses = [f"{valmap.get(l, l)} {c} {valmap.get(r, r)}"
               for l, c, r, _ in ens]
    return prim, args, out, clauses


def procedure_call(st, definitions, slots):
    """The procedure method a step invokes, or None for a normal step."""
    if st.get("type") != "call":
        return None
    defn = None
    for sl in slots:
        if sl.get("kind") == "instance" and sl.get("name") == st["inst"]:
            defn = definitions.get(sl["definition"])
            break
    if defn is None:
        defn = definitions.get(st["inst"])      # a stateless definition, by name
    if defn is None:
        return None
    meth = defn["methods"].get(st["method"])
    return meth if meth and meth.get("procedure") is not None else None


def _rv(v, rmap):
    """Rename one VALUE token via rmap. `INSTANCE.FIELD` renames its HEAD only:
    the instance is a local of the splice and gets a fresh name, the field is
    part of its definition and never moves."""
    inst, dot, field = v.partition(".")
    if dot:
        return f"{rmap.get(inst, inst)}.{field}"
    return rmap.get(v, v)


def _rexpr(s, rmap):
    """Rename the bare words of an arithmetic/condition expression, leaving the
    INSIDE of string literals alone (a local named `key` must not rewrite the
    text of "key")."""
    def words(t):
        return re.sub(r"\b\w+\b", lambda m: rmap.get(m.group(0), m.group(0)), t)
    out, i = [], 0
    for m in re.finditer(r'"[^"]*"', s):
        out.append(words(s[i:m.start()])); out.append(m.group(0)); i = m.end()
    out.append(words(s[i:]))
    return "".join(out)


def _rename_slot(s, rmap):
    s["name"] = rmap.get(s["name"], s["name"])
    if s.get("kind") == "buffer":
        s["size"] = rmap.get(s["size"], s["size"])
    if s.get("lens"):                   # `already V over BACKING [+ OFFSET]`:
        s["lens"] = rmap.get(s["lens"], s["lens"])          # the backing is a
        if isinstance(s.get("lens_off"), str):              # local too, and the
            s["lens_off"] = _rexpr(s["lens_off"], rmap)     # offset an expression
    if s.get("kind") == "instance":
        s["init"] = {k: _rv(v, rmap) for k, v in s.get("init", {}).items()}
        if s.get("pending"):
            s["pending"] = {k: (_rv(v[0], rmap), v[1])
                            for k, v in s["pending"].items()}


def _retarget_field_assign(s, field):
    """`FIELD is VALUE` inside a spliced template, where FIELD is one of the
    instance's own view fields. The rename turned the target into a view ACCESS
    -- `[addr : width] as ...` for bytes, `INST.FIELD` for bits -- and
    neither is a scalar slot, nor (for a bit) even a C lvalue. So re-shape the
    step into the store the program level would have emitted for that same
    text: a template writes a field exactly as a program does, through one
    emitter."""
    if s.get("clauses") is not None:
        fail(f"line {s['line']}: a conditional assign cannot write the view "
             f"field '{field}' -- compute the value into a scalar first, then "
             f"write the field")
    m = re.fullmatch(r"\[(.+?) : (\d+)\](?: as (.+))?", s["name"])
    if m:                                   # a byte field: a plain store
        words = (m.group(3) or "").split()
        new = {"type": "store", "addr": m.group(1), "size": m.group(2),
               "value": s["expr"], "signed": "signed" in words,
               "big": "big" in words, "line": s["line"]}
    else:
        m = re.fullmatch(r"(\w+)\.(\w+)", s["name"])
        if m is None:
            return                          # not a view access -- leave it be
        new = {"type": "fstore", "field": m.group(2), "inst": m.group(1),
               "value": s["expr"], "line": s["line"]}
    s.clear()
    s.update(new)


# ------------------------------------------------------------------ the steps
# THE STEP SCHEMA. A parsed step is a dict with a `type`; this table is the one
# place that says which fields each type carries and what a SPLICE has to do
# with each. Everything downstream that needs "the step types that X" derives
# its set from here rather than listing them again.
#
# That indirection is not decoration. The transpiler hand-listed those sets at
# five sites, and a list that drifted was a real, shipped bug: `_rename_step`
# omitted `scope_start` from its `cond` set, so a guarded scope inside a
# template kept the CALLER's names and the splice silently read the wrong
# variables. A derived set cannot drift -- add a field here or it does not
# exist, and `check_steps` refuses a step that carries anything not listed.
#
# The value of each field says how a splice treats it:
#   "rename"  a local NAME -- rewritten through the splice's rename map
#   "target"  ...a name being WRITTEN. Renamed too, but by `assign`'s own branch,
#             which has to notice when the rewrite turned it into a field store
#   "label"   ...a name that labels a scope rather than naming a value
#   "scope"   ...a name that REACHES a scope: what `leave`/`repeat` target
#   "expr"    an EXPRESSION -- every identifier in it rewritten
#   "cond"    a CONDITION -- an expression, and the thing five sites got wrong
#   "carry"   passed through untouched (line numbers, flags, sizes, sub-steps)
STEP_SCHEMA = {
    # -- values ------------------------------------------------------------
    "assign":      {"name": "target", "expr": "expr", "clauses": "expr",
                    "default": "expr", "force_cmov": "carry", "pname": "carry",
                    "line": "carry"},
    "store":       {"addr": "expr", "value": "expr", "cond": "cond",
                    "size": "carry", "signed": "carry", "big": "carry",
                    "vol": "carry", "kind": "carry", "line": "carry"},
    "fstore":      {"inst": "rename", "field": "carry", "value": "expr",
                    "cond": "cond", "line": "carry"},
    "atomic":      {"addr": "expr", "argstr": "expr", "capture": "rename",
                    "op": "carry", "order": "carry", "size": "carry",
                    "line": "carry"},
    "fence":       {"order": "carry", "line": "carry"},
    # -- resources ---------------------------------------------------------
    "construct":   {"name": "rename", "conns": "expr", "alts": "carry",
                    "recover": "carry", "line": "carry"},
    "adopt":       {"name": "rename", "inst_ref": "carry", "line": "carry"},
    # -- calls -------------------------------------------------------------
    "call":        {"inst": "rename", "method": "carry", "conns": "expr",
                    "alts": "carry", "recover": "carry", "line": "carry"},
    "bare":        {"op": "carry", "conns": "expr", "alts": "carry",
                    "recover": "carry", "line": "carry"},
    # -- checks ------------------------------------------------------------
    "guard":       {"cond": "cond", "ref": "carry", "line": "carry"},
    # -- scopes and jumps --------------------------------------------------
    "loop_start":  {"name": "label", "line": "carry"},
    # `loop_end` carries the loop's name for the PARSER (close_scope matches the
    # trailing `repeat` against it); the planner takes the name off its own
    # scope stack, so this copy is never read after parsing and never renamed.
    "loop_end":    {"name": "carry", "cond": "cond", "back": "carry",
                    "line": "carry"},
    "loop_exit":   {"name": "scope", "cond": "cond", "line": "carry"},
    "loop_again":  {"name": "scope", "cond": "cond", "line": "carry"},
    "scope_start": {"cond": "cond", "line": "carry"},
    "scope_end":   {"line": "carry"},
    # -- branching ---------------------------------------------------------
    "branch":      {"label": "label", "default_body": "carry",
                    "roads": "carry", "line": "carry"},
}

# The sets five sites used to spell out by hand, now derived. Each reads as the
# question it answers, and none of them can fall behind the table.
def _by_name_role(*roles):
    return {t for t, f in STEP_SCHEMA.items() if f.get("name") in roles}

RENAMED_NAME = _by_name_role("rename", "label", "scope")  # the shared rename
JUMPS        = _by_name_role("scope")          # `leave NAME` / `repeat NAME`
NOT_A_READ   = _by_name_role("target", "label")   # a write target or a label
HAS_COND     = {t for t, f in STEP_SCHEMA.items() if f.get("cond") == "cond"}


def check_steps(steps, where=""):
    """Every step must have a declared type and carry only declared fields.
    Cheap, and it turns a typo'd key -- which used to be silently ignored,
    since a dict takes anything -- into a stop with a line number."""
    for st in steps:
        t = st.get("type")
        if t is None:
            continue                     # plan steps and markers have no `type`
        known = STEP_SCHEMA.get(t)
        if known is None:
            fail(f"{where}internal: step type {t!r} is not in STEP_SCHEMA "
                 f"(line {st.get('line')})")
        extra = set(st) - set(known) - {"type"}
        if extra:
            fail(f"{where}internal: step {t!r} at line {st.get('line')} carries "
                 f"{sorted(extra)}, which STEP_SCHEMA does not declare")
        if t == "branch":
            check_steps(st.get("default_body") or (), where)
            for road in st.get("roads") or ():
                check_steps(road.get("body") or (), where)


def _walk_steps(steps):
    """Every step in a body, ROADS INCLUDED. A road holds steps like any other
    scope, so a loop opened in one is just as much a local of the template as a
    loop on its spine -- and `_rename_step` already recurses this way. Walking
    only the spine meant a `NAME goes` inside a road kept its written name, and
    a second splice of that template emitted the label twice (a duplicate label,
    caught by the C compiler rather than by us)."""
    for s in steps:
        yield s
        if s.get("type") == "branch":
            yield from _walk_steps(s.get("default_body", ()))
            for road in s.get("roads", ()):
                yield from _walk_steps(road.get("body", ()))


def _rename_step(s, rmap):
    t = s.get("type")
    if t in RENAMED_NAME:
        s["name"] = rmap.get(s["name"], s["name"])
    if t == "call":
        s["inst"] = rmap.get(s["inst"], s["inst"])
    if "conns" in s:                    # rename each actual, NEVER the port key
        s["conns"] = [(p, _rexpr(a, rmap), ln) for p, a, ln in s["conns"]]
    if t == "assign":
        _target = s["name"]
        s["name"] = rmap.get(s["name"], s["name"])
        if s.get("clauses") is not None:
            s["clauses"] = [(_rexpr(v, rmap), _rexpr(c, rmap))
                            for v, c in s["clauses"]]
            if s.get("default"):
                s["default"] = _rexpr(s["default"], rmap)
        else:
            s["expr"] = _rexpr(s["expr"], rmap)
        if s["name"] != _target and not re.fullmatch(r"\w+", s["name"]):
            _retarget_field_assign(s, _target)    # writing the view's own field
            return          # (now a store/fstore, built from ALREADY-renamed
                            # text -- falling through would rename it twice, and
                            # a substitution that still contains the field name
                            # (`tag` -> `tag of h`) would grow on each pass)
    if t == "store":
        s["value"] = _rexpr(s["value"], rmap)   # a stored VALUE is an expression
        s["addr"] = _rexpr(s["addr"], rmap)
    if t == "fstore":                           # `INST.FIELD is VALUE`
        s["inst"] = rmap.get(s["inst"], s["inst"])   # (never the field name)
        s["value"] = _rexpr(s["value"], rmap)
    if t == "atomic":
        s["addr"] = _rexpr(s["addr"], rmap)
        if s.get("argstr"):
            s["argstr"] = _rexpr(s["argstr"], rmap)
        if s.get("capture"):
            s["capture"] = rmap.get(s["capture"], s["capture"])
    if t in HAS_COND and s.get("cond"):
        s["cond"] = _rexpr(s["cond"], rmap)
    if t == "branch":                       # the label is a local, and both the
        s["label"] = rmap.get(s["label"], s["label"])   # inline road and every
        for sub in s.get("default_body", ()):           # cold road hold steps
            _rename_step(sub, rmap)
        for road in s.get("roads", ()):
            road["guard"] = _rexpr(road["guard"], rmap)
            for sub in road.get("body", ()):
                _rename_step(sub, rmap)


def inline_procedure(meth, st, cid, definitions, slots, prims):
    """Expand one procedure call into (slots, steps). The body is parsed as a
    mini-program, then the caller's actuals are substituted for the parameters
    and every local slot / loop label is made unique to this call site (cid).
    Renaming works on the parsed structure -- so a port name (the key of a
    wiring) is left alone even when it collides with a local (`buffer`)."""
    actual_of = {}
    for p, a, ln in st["conns"]:
        actual_of[p] = a
    for p in meth["params"]:
        if p not in actual_of:
            fail(f"line {st['line']}: '{meth['name']}' parameter '{p}' is "
                 "not connected")
    inst = next((sl for sl in slots if sl.get("kind") == "instance"
                 and sl.get("name") == st["inst"]), None)
    idefn = definitions.get(inst["definition"]) if inst is not None else None
    bound = set(meth["params"])
    if idefn is not None:                 # the resource's own state is not local
        bound |= {p for p in idefn.get("flat", ()) if re.fullmatch(r"\w+", p)}
    bslots, bsteps = [], []
    parse("program is\n" + "\n".join(meth["procedure"]), definitions, bslots,
          bsteps, [], prims, {}, bound=bound, procedure=True,
          namespace=meth.get("namespace"))
    # a TEMPLATE BODY is its own parse, so it needs its own check -- and it is
    # the half that matters, because a splice is where a mis-declared field
    # turns into the caller's names being read by the callee
    check_steps(bsteps, f"in template '{meth['name']}': ")
    # A template's locals are PRIVATE to the splice -- they are renamed per call
    # site, so nothing outside can read one. That makes a local nobody reads as
    # dead as a program-level scalar, and the same check applies. The body is
    # re-parsed from captured lines with comments and blanks already dropped, so
    # its line numbers do not map back to the file; point at the template itself.
    for _sl in dead_scalars(bslots, scalar_reads(bslots, bsteps), bound):
        fail(f"line {meth['line']}: '{meth['name']}' declares '{_sl['name']}', "
             "which nothing in it reads -- remove it, or is the name a typo? (a "
             "template's locals are private to the splice, so no caller can use "
             "one)")
    # `gcc asm` marks an output `&` when it may be written before the inputs are
    # read. A template is a splice, so the same hazard exists -- and unlike a
    # function call there is no copy at the boundary. If one actual is bound to
    # two ports and the body ASSIGNS one of them, the other's reads would see the
    # clobbered value. Reject rather than answer wrongly.
    #
    # Only direct assignment counts. Writing THROUGH a parameter (`[o + i : 8] is
    # v`) leaves the parameter itself alone, and passing one buffer as several
    # ports is legitimate and common (squaring: `o is c / a is c / b is c`).
    _written = {s["name"] for s in bsteps
                if s.get("type") == "assign" and s["name"] in meth["params"]}
    if _written:
        _by_actual = {}
        for p, a, ln in st["conns"]:
            _by_actual.setdefault(a, []).append(p)
        for a, ports in _by_actual.items():
            clobbered = [p for p in ports if p in _written]
            if len(ports) > 1 and clobbered:
                other = next(p for p in ports if p != clobbered[0])
                fail(f"line {st['line']}: '{meth['name']}' assigns '{clobbered[0]}'"
                     f" and also uses '{other}', but both are bound to '{a}' -- a"
                     " template is spliced in place, so the write happens before"
                     " the read and the read would see the new value. Bind them"
                     " to different slots.")
    # A template's control flow is its own. `leave` names a loop, and a name is
    # the one thing a splice cannot make hygienic on its own: an unrenamed
    # `leave serve` would bind to whatever loop the CALLER happened to call
    # `serve`, so a template could jump out of a program it knows nothing about.
    # A TEMPLATE IS A SCOPE TOO -- the body already had one (that is how a
    # resource it acquires gets released at the splice's end); now it has the
    # name to go with it, so `leave NAME` is an early return and `repeat NAME`
    # restarts the body. The scope is named per splice, like the locals, and the
    # body's own mentions of the template's name are rewritten to match.
    _own_loops = {s["name"] for s in _walk_steps(bsteps)
                  if s.get("type") == "loop_start"}
    _own_loops |= {s["label"] for s in _walk_steps(bsteps)   # its own crossroads:
                   if s.get("type") == "branch"}   # a road is a scope too, and
    _scope = f"{meth['name']}_{cid}"                # `leave LABEL` rejoins it
    for _s in _walk_steps(bsteps):
        if _s.get("type") not in JUMPS:
            continue
        if _s["name"] == meth["name"]:
            _s["name"] = _scope                  # the template's own scope
            continue
        if _s["name"] == "program":
            continue                             # the one scope that always
                                                 # encloses a splice, so naming
                                                 # it is not a guess
        if _s["name"] not in _own_loops:
            _w = ("repeats" if _s["type"] == "loop_again" else "leaves")
            fail(f"line {meth['line']}: '{meth['name']}' {_w} "
                 f"'{_s['name']}', which is neither itself nor one of its own "
                 "loops -- a template is spliced, not called, so a leave that "
                 "reached out of it would jump out of whatever program used "
                 f"it. Leave `{meth['name']}` or a loop it opens, or hand the "
                 "decision back through a port.")
    locals_ = {s["name"] for s in bslots}
    locals_ |= {s["name"] for s in _walk_steps(bsteps)
                if s.get("type") == "loop_start"}
    locals_ |= {s["label"] for s in _walk_steps(bsteps)
                if s.get("type") == "branch"}
    locals_ -= set(meth["params"])
    rmap = {}
    # A method called ON AN INSTANCE sees the instance's fields by name, exactly
    # as a single-call method does (`wire_call` binds the same `defn["flat"]` to
    # their storage cells). Bind them FIRST, so an explicit parameter or a local
    # of the same name still wins.
    if inst is not None:
        if idefn is not None:
            _pl = idefn.get("playout") or {}
            for path in idefn.get("flat", ()):
                if (re.fullmatch(r"\w+", path) and path not in meth["params"]
                        and path not in locals_):
                    # `in register` owns no bytes, so its fields are NOT a view
                    # over a block -- they are the state cells below.
                    _data = inst.get("lens") or is_pure_layout(idefn)
                    _back = inst.get("lens")
                    if (_data and _back
                            and (_back in REGISTER_WORDS or _back in SCALAR_WORDS)):
                        # the backing is a REGISTER WORD, so `[BASE + k : w]` is
                        # the wrong text: on a scalar that spelling already means
                        # "dereference the address in BASE". Substitute the mereo
                        # FIELD access and let the one field emitter slice it.
                        rmap[path] = f"{inst['name']}.{path}"
                    elif _data and path in _pl:
                        # a lens's fields ARE its backing's bytes, and the body is
                        # re-parsed as mereo -- so substitute a mereo access, not
                        # the C cell (which would not parse).
                        _off, _w, _sg, _big = _pl[path]
                        _at = [inst["lens"] if inst.get("lens")
                               else inst["name"]]      # owning: the name IS the
                        if inst.get("lens") and str(               # block address
                                inst.get("lens_off", "0")) != "0":
                            _at.append(str(inst["lens_off"]))
                        if _off:
                            _at.append(str(_off))
                        _v = " ".join(w for w, on in
                                      (("signed", _sg), ("big", _big)) if on)
                        rmap[path] = (f"[{' + '.join(_at)} : {_w}]"
                                      + (f" as {_v}" if _v else ""))
                    elif _data and path in (idefn.get("bitfields") or {}):
                        # a flag lens's fields are BITS in the backing word, and
                        # a bit is not a C lvalue -- so substitute the mereo
                        # access and let the ordinary emitter mask and shift.
                        rmap[path] = f"{inst['name']}.{path}"
                    else:
                        rmap[path] = state_cell(inst["name"], path, idefn,
                                                inst.get("backing"))
    rmap.update(actual_of)
    for name in locals_:
        rmap[name] = f"{meth['name']}_{cid}_{name}"
    for s in bslots:
        _rename_slot(s, rmap)
    for s in bsteps:
        if s.get("type") == "guard":         # name the diagnostic after the
            s["ref"] = meth["name"]          # method, not a mangled local
        _rename_step(s, rmap)
    return bslots, bsteps


def expand_procedures(definitions, slots, steps, prims):
    """Replace each procedure-method call with its inlined body, REPEATEDLY to a
    fixpoint -- so a procedure that calls another procedure is fully spliced
    (mereo is function-free; every call is a splice). A global call-id keeps
    each inline's locals unique across passes; the cap catches an accidentally
    recursive (self/cyclic) procedure, which can't terminate when inlined."""
    cid = [0]

    def one_pass(steps):
        out, changed = [], False
        for st in steps:
            if st.get("type") == "branch":
                # A crossroad's roads are step lists like any other, so a call in
                # one splices exactly as it does on the spine. They were skipped
                # before -- expansion only ever walked the spine -- which is why
                # a road could not call a template: the call survived to the
                # planner, which had no body to plan.
                st["default_body"], c = one_pass(st["default_body"])
                changed = changed or c
                for road in st["roads"]:
                    road["body"], c = one_pass(road["body"])
                    changed = changed or c
                out.append(st)
                continue
            meth = procedure_call(st, definitions, slots)
            if meth is None:
                out.append(st)
                continue
            changed = True
            cid[0] += 1
            bslots, bsteps = inline_procedure(meth, st, cid[0], definitions, slots,
                                              prims)
            slots.extend(bslots)
            # a procedure's scalar locals are function-scope in the emitted C
            # (declared once), so a procedure CALLED IN A LOOP would see last
            # call's values. Re-initialise them to their declared value on entry
            # -- C function-local semantics -- so a loop counter starts fresh.
            resets = [{"type": "assign", "name": s["name"], "expr": s["init"],
                       "pname": None, "line": st["line"]}
                      for s in bslots if s.get("kind") == "scalar"]
            # The inlined body is a NAMED scope: any resource it acquires is
            # released at its (spliced) end -- C++ function-body semantics --
            # and the name gives `leave` somewhere to land and `repeat`
            # somewhere to go back to. Both labels are dropped unless the body
            # actually targets them, so a template that does neither emits
            # exactly what the anonymous scope emitted before.
            _scope = f"{meth['name']}_{cid[0]}"
            out.append({"type": "loop_start", "name": _scope,
                        "line": st["line"]})
            out.extend(resets)
            out.extend(bsteps)
            out.append({"type": "loop_end", "name": _scope, "cond": None,
                        "back": False, "line": st["line"]})
        return out, changed

    for _ in range(64):
        steps, changed = one_pass(steps)
        if not changed:
            return steps
    fail("procedure expansion did not terminate -- a procedure method calls "
         "itself (directly or in a cycle); mereo is function-free, so a "
         "procedure cannot recurse")


def resolve_lenses(definitions, slots):
    """Work out each lens's backing BEFORE procedures are spliced.

    Splicing bakes every state cell into the caller's namespace, and a lens's
    cells live in its BACKING -- so if the backing is still unknown at that
    point, the splice bakes the register-scalar form instead, which a lens never
    emits. check_slots resolves lenses too (it must: a splice can create one), so
    this is a pre-pass, not a replacement."""
    # a register backing is claimed here too: REGISTER_WORDS is filled by
    # check_slots, which runs AFTER this, and without it a lens over a word
    # would resolve to a bogus address instead of a slice of it.
    for s in slots:
        if s.get("kind") == "buffer" and s.get("place") == "register":
            if str(s["size"]).isdigit() and int(s["size"]) in (1, 2, 4, 8):
                REGISTER_WORDS.setdefault(s["name"], int(s["size"]))
        elif s.get("kind") == "scalar":
            SCALAR_WORDS.add(s["name"])
    bufs = {}
    for s in slots:
        if s.get("kind") == "buffer":
            bufs[s["name"]] = s
        elif s.get("kind") == "instance" and not s.get("lens"):
            c = definitions.get(s["definition"])
            if c is not None and (c.get("playout") or c.get("bitfields")):
                bufs[s["name"]] = {"size": str(c.get("psize")
                                               or c.get("bitwidth") or 0)}
    for s in slots:
        if (s.get("kind") == "instance" and s.get("lens")
                and "backing" not in s and s.get("lens") in bufs):
            defn = definitions.get(s["definition"])
            if defn is None:
                continue
            span = defn.get("psize") or defn.get("bitwidth")
            if span:
                _t = lens_target(s, definitions, bufs, span)
                if not isinstance(_t, tuple):     # a register backing carries no
                    s["backing"] = _t             # address; check_slots holds it



def plan(definitions, slots, steps, overrides):
    elaborate_classes(definitions)
    resolve_lenses(definitions, slots)
    steps = expand_procedures(definitions, slots, steps, PRIMITIVES)
    scalars, buffers, instances = check_slots(definitions, slots)

    if not steps and not HAS_PROGRAM:
        fail("no `program is` -- this file declares things but never uses them")
    final = steps[-1] if steps else None
    if (final is None or final["type"] != "bare"
            or not PRIMITIVES.get(final["op"], {}).get("noreturn")):
        # THE PROGRAM IS A SCOPE, and reaching its `end` leaves it -- releasing
        # everything, exactly as `leave program` does from the middle. So no
        # exit step is written, and one is synthesised here.
        #
        # The status is not the program's to hand over: `_status` belongs to the
        # emitter, every `ensure` writes its stage number there on the way to the
        # tower, and a program that simply ends leaves it at 0. A non-zero status
        # therefore means one thing only -- something failed and mereo derived
        # it. A program that genuinely wants to hand the KERNEL a number calls
        # the kernel: `linux.exit (status is n)` as its last step, which is a
        # noreturn primitive and takes this branch's place.
        exit_prim = next((nm for nm, pr in PRIMITIVES.items()
                          if pr.get("noreturn")), None)
        if exit_prim is None:
            fail("a program needs a noreturn primitive to end with -- "
                 'include a library that declares one (`exit is final assembly '
                 '"syscall"`, as linux.mereo does)')
        final = {"type": "bare", "op": exit_prim, "conns": [], "recover": None,
                 "alts": [], "line": steps[-1]["line"] if steps else 1,
                 "implicit": True}
        steps = steps + [final]
    for st in steps:
        if st["type"] != "bare":
            continue
        prim = PRIMITIVES.get(st["op"])
        if prim is None:
            _d = definitions.get(st["op"])
            if _d is not None and kind_of(_d) == "template group":
                fail(f"line {st['line']}: '{st['op']}' is a template group, so "
                     f"the call names the template in it: `TEMPLATE {st['op']} "
                     f"where` (has: {', '.join(_d['methods'])}). Only a template "
                     "written on its own is called by its own name.")
            fail(f"line {st['line']}: unknown primitive '{st['op']}'")
        if not prim["noreturn"]:
            fail(f"line {st['line']}: bare '{st['op']}' -- fallible primitives "
                 "must live in a resource so they carry an `ensure`")
        if st is not final:
            fail(f"line {st['line']}: noreturn step '{st['op']}' must be the "
                 "final step")

    # the status is implicit (an emitter-owned variable) when the final
    # noreturn step is bare; a wired scalar takes its place otherwise
    stage_slot = None
    if not final["conns"]:
        stage_slot = "_status"
    elif len(final["conns"]) == 1 and final["conns"][0][1] in scalars:
        stage_slot = final["conns"][0][1]

    live, plan_steps, fallible, recovers, attempts = [], [], [], [], []
    # `live` is the CURRENT scope stack (shrinks when a loop/block/method scope
    # closes); `tower_order` is every instance that ever needed a release floor,
    # never truncated, so the fault tower keeps a floor for each. Normal exit
    # enters the tower at the outermost-scope top (`live` at exit); inner-scope
    # floors remain above it for fault jumps only (their normal release already
    # happened at their own scope exit).
    tower_order = []
    block_entries = []      # live-set size at each open `scope` block, a stack
    block_labels = []       # ...and, for a GUARDED one, where its guard skips to
    enclosing = {}          # resource -> the one directly beneath it in `live`
                            # when acquired (its enclosing floor), or None. The
                            # tower chains each floor to its enclosing one, so a
                            # fault releases exactly the live set even when a
                            # closed inner scope's floor sits between (tree tower).

    def record_live(name):
        enclosing[name] = live[-1] if live else None
        live.append(name)
        tower_order.append(name)

    def releases_for(names):
        """Cleanup calls to release `names` in reverse acquisition order -- the
        shared shape of a loop iteration, a block dedent, and a branch road."""
        out = []
        for name in reversed(names):
            idefn = definitions[instances[name]["definition"]]
            for cprim, cargs in idefn["cleanup"]:
                out.append({"pname": cprim,
                            "args": [lit_c(a) if is_int(a) or is_str(a)
                                     else state_cell(name, a, idefn, instances[name].get("backing"))
                                     for a in cargs]})
        return out
    n_resume = 0
    loop_id = 0
    loops_left = set()      # scopes some `leave` jumps out of, and
    loops_back = set()      # scopes some `repeat` jumps back to. A scope emits
                            # each of its two labels only if something targets
                            # it, so one nothing jumps to is exactly a `scope`
    loop_stack = []         # (live-set size, label) per open loop, innermost last
    constructed = set()
    branch_colds = []           # cold `when`-road blocks, per branch crossroad

    def callee(name, line):
        """Resolve a call target. Normally a declared instance; but a stateless
        definition (no state to hold) is called DIRECTLY by name -- `user
        identity where ...` -- with no instance ceremony. One WITH state
        still needs an instance to name whose state a method reaches."""
        inst = instances.get(name)
        if inst is not None:
            return inst, definitions[inst["definition"]]
        defn = definitions.get(name)
        if defn is None:
            fail(f"line {line}: unknown instance or definition '{name}'")
        if defn["flat"]:
            fail(f"line {line}: '{name}' has state -- construct or adopt an "
                 "instance to call its methods")
        return ({"name": name, "definition": name, "mode": "adopted",
                 "borrowmap": {}, "lenders": set()}, defn)

    # ONE step, planned into `into`. The spine passes `plan_steps`; a branch
    # road passes its own list and gets the IDENTICAL treatment -- which is
    # the point. A road is a mini-spine, so a store, an `ensure`, a
    # construction, an `or continue`, and a spliced template body all mean
    # there exactly what they mean here, because it is the same code.
    def plan_one(st, into, cold=False):
        nonlocal n_resume, loop_id
        if st["type"] == "assign":           # `X is EXPR` -- recompute a scalar
            if st["name"] not in scalars:
                fail(f"line {st['line']}: '{st['name']}' is not a scalar slot "
                     "(declare it with `NAME is NUMBER` before assigning)")
            if st.get("clauses") is not None:
                # a conditional cascade. Compile each clause once (condition +
                # value), then lower it two ways: the default nested ternary
                # (GCC's cost model chooses cmov or branch), or -- under
                # MEREO_CMOV -- a forced `cmov` per clause via inline asm, so the
                # choice is guaranteed branchless whatever the values.
                fallback = (resolve_value(st["default"], scalars, buffers,
                                          st["line"])
                            if st.get("default") else st["name"])
                clause_cv = [(render_choice_cond(cond, scalars, buffers,
                                                 st["line"]),
                              resolve_value(val, scalars, buffers, st["line"]))
                             for val, cond in st["clauses"]]
                if st.get("force_cmov"):
                    # `branchless` is a REQUIREMENT, not a hint: it must be
                    # honourable, or say why not. A conditional move computes
                    # every arm, so a clause that reads through a scalar
                    # ADDRESS -- the `p != 0` guard people write -- would do
                    # the read before the test and the guard would guard
                    # nothing. The plain `when` form branches there, which is
                    # exactly what makes it a guard.
                    for _v, _c in st["clauses"] + ([(st["default"], None)]
                                                   if st.get("default") else []):
                        _why = cannot_speculate(_v, scalars)
                        if _why:
                            fail(f"line {st['line']}: `branchless` cannot be "
                                 f"honoured -- `{_v}` cannot be computed before "
                                 f"the condition, because {_why}, and a "
                                 "conditional move computes both arms. Drop "
                                 "`branchless`: the plain `when` form branches, "
                                 "which is what makes the guard real.")
                if st.get("force_cmov") or os.environ.get("MEREO_CMOV"):
                    # apply clauses low-priority-first, so the first (highest-
                    # priority) clause makes the last, winning move.
                    parts = ([f"{st['name']} = ({fallback});"]
                             if st.get("default") else [])
                    for cond_c, val_c in reversed(clause_cv):
                        parts.append(_CMOV_TMPL.format(
                            cond=cond_c, x=st["name"], val=val_c))
                    into.append({"stmt": " ".join(parts), "pname": None})
                    return
                expr_c = fallback
                for cond_c, val_c in reversed(clause_cv):
                    expr_c = f"(({cond_c}) ? ({val_c}) : ({expr_c}))"
            else:
                expr_c = resolve_value(st["expr"], scalars, buffers, st["line"])
            into.append(
                {"assign": st["name"], "pname": None, "expr_c": expr_c})
            return

        if st["type"] == "fence":            # a standalone memory barrier
            into.append(
                {"stmt": f"__atomic_thread_fence({_ATOMIC_ORDER[st['order']]})",
                 "pname": None})
            return

        if st["type"] == "atomic":           # `[ADDR:N] atomic OP …`
            addr_c = resolve_value(st["addr"], scalars, buffers, st["line"])
            args = [a.strip() for a in st["argstr"].split(" set ")] \
                if st["argstr"] else []
            args = [resolve_value(a, scalars, buffers, st["line"]) for a in args]
            c = atomic_c(st["op"], st["order"], st["size"], addr_c, args,
                         st["line"])
            if st["capture"]:
                if st["capture"] not in scalars:
                    fail(f"line {st['line']}: the atomic result must land in a "
                         f"scalar slot, not '{st['capture']}'")
                into.append({"assign": st["capture"], "pname": None,
                                   "expr_c": c})
            else:
                into.append({"stmt": c, "pname": None})
            return

        if st["type"] == "store":            # `[ADDR : N] [as VIEW] is VALUE`
            # `... is VALUE when COND` -- the guard rides on whichever
            # statement this store lowers to. There is no conditional store on
            # x86-64 or A64 (A32's `STRNE` is where the form comes from), so it
            # is one `if`; `when` states the dependence and lets the target
            # lower it however it can, which `branchless` refuses to accept.
            when_c = (render_choice_cond(st["cond"], scalars, buffers,
                                         st["line"])
                      if st.get("cond") else None)
            for tok in re.findall(r"[A-Za-z_]\w*", st["addr"]):
                if buffers.get(tok, {}).get("const"):
                    fail(f"line {st['line']}: cannot write to constant buffer "
                         f"'{tok}' (it lives in read-only .rodata)")
            val = resolve_value(st["value"], scalars, buffers, st["line"])
            _rw = re.match(r"^(\w+)\s*(?:\+(.*))?$", st["addr"].strip())
            if _rw and _rw.group(1) in REGISTER_WORDS:
                # a register word: the same store, as a masked read-modify-write
                if st.get("kind") == "float" or st.get("vol"):
                    why = ("a float view reinterprets BYTES, and a register word "
                           "has none" if st.get("kind") == "float" else
                           "volatile orders a MEMORY access, and a register word "
                           "is not memory")
                    fail(f"line {st['line']}: `as "
                         f"{st.get('kind') or 'volatile'}` on "
                         f"`[{_rw.group(1)} ...]` -- '{_rw.group(1)}' is "
                         f"`in register`: {why}")
                if str(st["size"]) not in ("1", "2", "4", "8"):
                    fail(f"line {st['line']}: memory width must be 1, 2, 4, or 8 "
                         f"bytes, not '{st['size']}'")
                into.append(
                    {"stmt": register_write(
                        _rw.group(1),
                        register_offset(_rw.group(1), _rw.group(2), st["line"]),
                        int(st["size"]), st.get("big"), val, st["line"]),
                     "when_c": when_c, "pname": None})
                return
            if st.get("kind") == "float":    # write IEEE-754 (single/double)
                stype = {"4": "float", "8": "double"}.get(st["size"])
                if stype is None:
                    fail(f"line {st['line']}: a `float` store needs width 4 or "
                         f"8 bytes, not {st['size']}")
            else:
                if st.get("big") and int(st["size"]) > 1:
                    val = big_write(val, int(st["size"]))   # network order
                stype = width_type(st["size"], st["line"])
            if st.get("vol"):                # MMIO / shared memory: a real store
                stype = "volatile " + stype
            into.append(
                {"store_addr": resolve_value(st["addr"], scalars, buffers,
                                             st["line"]),
                 "store_val": val,
                 "store_type": stype,
                 "when_c": when_c, "pname": None})
            return

        if st["type"] == "fstore":           # `INST.FIELD is VALUE` -- write
            # `... is VALUE when COND` -- the guard rides on whichever
            # statement this store lowers to. There is no conditional store on
            # x86-64 or A64 (A32's `STRNE` is where the form comes from), so it
            # is one `if`; `when` states the dependence and lets the target
            # lower it however it can, which `branchless` refuses to accept.
            when_c = (render_choice_cond(st["cond"], scalars, buffers,
                                         st["line"])
                      if st.get("cond") else None)
            ff = flag_field_c(f"{st['inst']}.{st['field']}", buffers,
                              st["line"])
            if ff is not None:               # a flag view: masked read-modify-write
                _, cell, ut, lo, mask, cast = ff
                val = resolve_value(st["value"], scalars, buffers, st["line"])
                into.append({"store_bits": (cell, ut, lo, mask, val, cast),
                             "when_c": when_c, "pname": None})
                return
            sf = layout_field_c(f"{st['inst']}.{st['field']}", buffers,
                                st["line"])
            if sf is None:
                if any(i == st["inst"] for i, _ in INSTANCE_FIELDS):
                    # a resource's state is PUBLIC to read but settled once the
                    # thing is held: it is written by its own `acquire`, or by
                    # `already`/`adopted` at construction, and never after --
                    # the release tower is derived from it.
                    fail(f"line {st['line']}: '{st['inst']}' state is settled "
                         "once acquired -- a resource's state is written by its "
                         "own `acquire`, or by `already`/`adopted` at "
                         "construction, and is read-only after, because the "
                         "release tower depends on it. Reading is fine: "
                         f"`{st['inst']}.{st['field']}`")
                fail(f"line {st['line']}: '{st['inst']}' is not a layout instance")
            _, off, width, _sg, big = sf
            val = resolve_value(st["value"], scalars, buffers, st["line"])
            rl = buffers[st["inst"]].get("reglens")
            if rl:                             # a slice of a register word: the
                word, base = rl                # same masked read-modify-write
                into.append(
                    {"stmt": register_write(word, base + off, width, big, val,
                                            st["line"]),
                     "when_c": when_c, "pname": None})
                return
            if big and width > 1:
                val = big_write(val, width)
            base = buffers[st["inst"]].get("addr", f"(long){st['inst']}")
            into.append(
                {"store_addr": f"({base} + {off})",
                 "store_val": val,
                 "store_type": width_type(str(width), st["line"]),
                 "when_c": when_c, "pname": None})
            return

        if st["type"] == "guard":            # `ensure COND` -- a callless failure
            # the predicate is the shared condition grammar; the record's value
            # is the condition's SUBJECT -- its left side (or the whole thing,
            # for a bare truthiness test).
            m = re.match(r"^(.+?) (is|<=|>=|==|!=|<|>) (.+)$", st["cond"])
            lhs = (m.group(1).strip() if m else st["cond"].strip())
            if stage_slot is None:
                fail(f"line {st['line']}: cannot derive the status slot for "
                     "`ensure` -- wire a scalar into the final noreturn step")
            pred_c = render_choice_cond(st["cond"], scalars, buffers,
                                        st["line"])
            errsrc_c = resolve_value(lhs, scalars, buffers, st["line"])
            ref = st.get("ref") or lhs
            # routes to the tower floor for the live set here (getpwuid's file
            # is live -> it is released), reports the violating value, exit 1
            ps = {"pname": None, "noreturn": False, "args": [], "out": None,
                  "clauses": [pred_c], "label": None,
                  "recover": None,
                  "gtarget": error_label(len(fallible) + 1, ref),
                  "resume": None, "stage": len(fallible) + 1, "ref": ref,
                  "ident": (None, ref), "errsrc": errsrc_c, "strings": [],
                  "code": "1", "line": st["line"],
                  "target": f"release_{live[-1]}" if live else final["op"]}
            fallible.append(ps)
            into.append(ps)
            return

        if st["type"] == "loop_start":       # `NAME goes` -- open a named scope
            loop_id += 1                      # (innermost last, LIFO nesting)
            _top = {"loop_top": st["name"], "pname": None}
            loop_stack.append((len(live), st["name"], _top))
            into.append(_top)
            return

        if st["type"] in JUMPS:
            if st["name"] == "program":
                # THE PROGRAM IS A SCOPE TOO -- and the one whose release ladder
                # already exists as the TOWER, shared by every fault path. So
                # `leave program` ENTERS the ladder instead of emitting a second
                # copy of it: release from the floor for whatever is live here,
                # then exit. That is precisely the graceful -EINTR/-EPIPE route,
                # with the status left at 0 and no record written.
                if st["type"] == "loop_again":
                    # `repeat program` -- back to the program's FIRST STEP, past
                    # the entry views and the signal dispositions, which are
                    # settled once and are not part of what repeats.
                    #
                    # It cannot enter the tower the way `leave program` does:
                    # the tower ends at `exit`, and this has somewhere else to
                    # go. So the releases are emitted HERE, inline, exactly as
                    # `repeat NAME` does for any other scope -- and by the same
                    # rule, since the program's entry set is empty, what it
                    # releases is everything live. No flag records how far it
                    # got, because the live set at this point is known when the
                    # program is compiled.
                    into.append({"loop_exit": PROGRAM_AGAIN,
                                 "releases": releases_for(live),
                                 "cond_c": (render_cond(st["cond"], scalars,
                                                        buffers, st["line"])
                                            if st.get("cond") else None),
                                 "pname": None})
                    return
                into.append({"loop_exit": (f"release_{live[-1]}" if live
                                           else final["op"]),
                             "releases": [],        # the tower performs them
                             "cond_c": (render_cond(st["cond"], scalars,
                                                    buffers, st["line"])
                                        if st.get("cond") else None),
                             "pname": None})
                return

            # `repeat NAME` and `leave NAME` are ONE jump with two targets: the
            # loop's top, or past its end. Both release the same thing --
            # everything taken since that loop began, which on the way out of an
            # inner loop or a road includes what those took.
            #
            # The target must be a loop this step SITS IN. That single rule is
            # what keeps the releases derivable: the live set where it lands is
            # the loop's entry set, a subset of the live set here by
            # construction, so the difference is exactly what to release. A jump
            # anywhere else could arrive with a live set that depends on the
            # path, which is a drop flag.
            _word = "repeat" if st["type"] == "loop_again" else "leave"
            _open = [i for i, (_e, nm, _t) in enumerate(loop_stack)
                     if nm == st["name"]]
            if not _open:
                _have = ", ".join(nm for _e, nm, _t in loop_stack) or "none"
                fail(f"line {st['line']}: `{_word} {st['name']}` -- "
                     f"'{st['name']}' is not a scope this sits inside (open "
                     f"here: {_have}). It can only target a scope AROUND it -- "
                     "an ancestor's start or end, never a sibling's and never "
                     "one already closed. That is what makes the releases on "
                     "the way there derivable: the live set where it lands is "
                     "that scope's entry set, so the difference is exactly "
                     "what to let go of.")
            _entry, _nm, _top = loop_stack[_open[-1]]  # innermost of that name
            if _top is None:
                # A ROAD. Its end is its crossroad's MERGE label, which already
                # exists -- every cold road rejoins through it -- so
                # `leave LABEL` is "release this road's own and rejoin now",
                # which is C's `break` in a switch case. It has no start: a road
                # is entered by the dispatch, so `repeat` would mean re-testing
                # the guards, and that is a loop.
                if st["type"] == "loop_again":
                    fail(f"line {st['line']}: `repeat {st['name']}` -- "
                         f"'{st['name']}' is a crossroad, and a road has no "
                         "start to go back to: it is entered by the dispatch, "
                         "not from its own top. Re-testing the guards is a "
                         "loop -- put the crossroad inside one and repeat "
                         "that.")
                _target = st["name"]              # the merge label
            elif st["type"] == "loop_exit":
                _target = f"{st['name']}_done"    # past the scope's end
                loops_left.add(st["name"])
            else:
                _target = st["name"]              # the scope's start label
                loops_back.add(st["name"])
            into.append({"loop_exit": _target,
                         "releases": releases_for(live[_entry:]),
                         "cond_c": (render_cond(st["cond"], scalars, buffers,
                                                st["line"])
                                    if st.get("cond") else None),
                         "pname": None})
            return                       # a jump, not a scope end: `live` is
                                         # unchanged for the fall-through path

        if st["type"] == "loop_end":
            # per-iteration cleanup: release everything acquired in the body
            # (reverse acquisition order), then loop back. `again` is an
            # unconditional back-edge; `again when COND` loops while COND holds
            # and falls through (exit) otherwise. The release happens before the
            # test, so both the back-edge and the fall-through exit are clean.
            loop_entry, loop_name, _top = loop_stack.pop()
            releases = releases_for(live[loop_entry:])
            _end = (f"{loop_name}_done" if loop_name in loops_left else None)
            if not (st.get("back", True) or loop_name in loops_back):
                _top["loop_top"] = None      # nothing jumps to the start
            if not st.get("back", True):
                # a named scope nothing repeats: release what it holds and fall
                # out. Same releases, no back-edge -- which is the only thing a
                # loop adds.
                into.append({"scope_release": releases, "exit_label": _end,
                             "pname": None})
            else:
                cond_c = (render_cond(st["cond"], scalars, buffers, st["line"])
                          if st.get("cond") else None)
                into.append({"loop_back": loop_name, "releases": releases,
                             "cond_c": cond_c, "pname": None,
                             "exit_label": _end})
            # the loop scope closes: its body resources were released per
            # iteration (above), so they leave the live set -- code after the
            # loop, and the normal-exit tower, must not release them again.
            # Their floors stay in `tower_order` for faults inside the loop.
            del live[loop_entry:]
            return

        if st["type"] == "scope_start":     # `scope` / `GUARD goes` -- a block
            block_entries.append(len(live))
            # A guarded block is an `if`: skip the body AND its releases when
            # the guard is false. Skipping both is right, not a shortcut -- the
            # body is what acquires, so on the not-taken path there is by
            # construction nothing to let go of.
            if st.get("cond"):
                loop_id += 1
                lbl = f"past_{loop_id}"
                block_labels.append(lbl)
                into.append({"scope_guard": render_cond(st["cond"], scalars,
                                                        buffers, st["line"]),
                             "skip": lbl, "pname": None})
            else:
                block_labels.append(None)
            return

        if st["type"] == "scope_end":       # dedent -- release the block's
            entry = block_entries.pop()      # resources (reverse) and pop them
            releases = []                    # out of the live set; floors stay
            for name in reversed(live[entry:]):   # in tower_order for faults
                idefn = definitions[instances[name]["definition"]]
                for cprim, cargs in idefn["cleanup"]:
                    releases.append(
                        {"pname": cprim,
                         "args": [lit_c(a) if is_int(a) or is_str(a)
                                  else state_cell(name, a, idefn, instances[name].get("backing"))
                                  for a in cargs]})
            into.append({"scope_release": releases, "pname": None,
                         "exit_label": block_labels.pop()})
            del live[entry:]
            return

        if st["type"] == "branch":
            # `LABEL likely goes`: the default road is promoted inline onto the
            # hot path; each cold `when` road becomes a detour, dispatched by
            # its guard and rejoining at the merge (the crossroad label). `is`
            # in a guard means ==.
            label = st["label"]
            # A crossroad may NEST INSIDE A COLD ROAD. It used to be refused, on
            # the reading that a crossroad's guarantee is "the dispatch is hot
            # and the roads are not" and a cold road has no hot path left to put
            # one on. But the guarantee is really RELATIVE -- the roads sit
            # further out than the dispatch -- and that holds perfectly well one
            # level down: the nested dispatch stays where its enclosing road is,
            # and its own roads are emitted past it, still in the cold tail.
            #
            # The refusal was not free. A template that branches carries its
            # crossroad into every splice, so `number text` (whose leading `-`
            # is a road) could not be used inside a road AT ALL -- a library
            # template's internal layout leaking into its callers' grammar.
            # Nested roads are marked so mereocheck holds them to the cold-region
            # rule instead of the spine rule.
            if not st["roads"]:
                fail(f"line {st['line']}: branch '{label}' has a `likely` road "
                     f"but no `when` road -- add a `{label} when GUARD goes` "
                     "past exit, or drop the branch")
            gplan = []
            for k, road in enumerate(st["roads"]):
                pred = render_choice_cond(road["guard"], scalars, buffers,
                                          road["line"])
                gplan.append({"pred": pred, "label": f"{label}_road_{k}"})
            def plan_road_body(body, out, cold_road):
                """A road body is a mini-spine, so plan it with the spine's own
                planner. It used to have a planner of its own that knew four
                step kinds -- assign, adopt, call, and the loop/block markers --
                which is why a template could not be spliced into a road: the
                first store or `ensure` in the body had nowhere to go. They are
                the same code now, so a road holds whatever the spine holds."""
                for cs in body:
                    plan_one(cs, out, cold_road)

            # each road is a lexical scope: resources it adopts release at its
            # end -- the likely road at the merge, a `when` road before it
            # rejoins. Floors stay in tower_order for faults inside the road.
            # It goes on the scope stack under the CROSSROAD's name (with no
            # start step, which is what marks it a road), so `leave LABEL`
            # inside a road rejoins the merge early, releasing that road's own.
            into.append({"branch_dispatch": gplan, "pname": None})
            likely_entry = len(live)
            loop_stack.append((likely_entry, label, None))
            plan_road_body(st["default_body"], into, cold)
            loop_stack.pop()
            rel = releases_for(live[likely_entry:])
            if rel:
                into.append({"scope_release": rel, "pname": None})
            del live[likely_entry:]
            into.append({"branch_merge": label, "pname": None})
            colds = []
            for k, road in enumerate(st["roads"]):
                road_entry = len(live)
                loop_stack.append((road_entry, label, None))
                rplan = []
                plan_road_body(road["body"], rplan, True)
                loop_stack.pop()
                rel = releases_for(live[road_entry:])
                if rel:
                    rplan.append({"scope_release": rel, "pname": None})
                del live[road_entry:]
                colds.append({"label": f"{label}_road_{k}", "back": label,
                              "plan": rplan, "nested": cold})
            branch_colds.append(colds)
            return

        if st["type"] == "bare":
            if st["recover"] is not None:
                fail(f"line {st['recover']['line']}: `or continue` must "
                     "follow a method call")
            if st["alts"]:
                fail(f"line {st['alts'][0]['line']}: `or where` must follow "
                     "a construction or a method call")
            prim = PRIMITIVES[st["op"]]
            conns = {p: (a, ln) for p, a, ln in st["conns"]}
            args = []
            for kind, port in prim["args"]:
                if port not in conns:
                    break
                actual, ln = conns.pop(port)
                args.append(resolve_value(actual, scalars, buffers, ln))
            for port, (_, ln) in conns.items():
                fail(f"line {ln}: '{st['op']}' has no port '{port}'")
            into.append({"pname": st["op"], "noreturn": True,
                               "args": args, "out": None, "clauses": [],
                               "label": st["op"], "recover": None,
                               "gtarget": None, "resume": None})
            return

        if st["type"] == "adopt":
            # assemble an instance from given values, no acquiring syscall, so
            # it cannot fail. If the resource has cleanup (an fd) it joins the
            # live set so the tower releases it; a pure value view (a span,
            # no cleanup) does not -- there is nothing to release.
            if st["name"] not in instances:
                return                  # a layout lens is a buffer, not an
                                          # instance -- nothing to adopt at runtime
            inst = instances[st["name"]]
            idefn = definitions[inst["definition"]]
            constructed.add(inst["name"])
            # only an OWNED adoption (`adopted`) with a resource joins the
            # tower; a borrowed view (`already`) never closes what it views
            if inst.get("own") and idefn["cleanup"]:
                record_live(inst["name"])
            # A FLAG VIEW is a word whose bits are named, so a value handed in
            # at adoption is a masked read-modify-write of that word, not an
            # assignment to a cell of its own. Emitting it as a cell store put
            # `m_echo = 1` into the output -- a name that was never declared, so
            # the generated C did not compile. Reuse the same `store_bits` shape
            # `m.echo is 1` already lowers to, one step per field.
            if idefn.get("bitfields") is not None:
                for path, val in inst["runinit"].items():
                    ff = flag_field_c(f"{inst['name']}.{path}", buffers,
                                      st["line"])
                    _, cell, ut, lo, mask, cast = ff
                    into.append({"store_bits": (cell, ut, lo, mask,
                                                resolve_value(val, scalars,
                                                              buffers,
                                                              st["line"]),
                                                cast),
                                 "when_c": None, "pname": None})
                return
            # A field's BYTE ORDER is part of the field, so a value handed in at
            # construction is swapped exactly as one stored later would be.
            # `state_cell` gives the lvalue and discards the reading -- it names
            # the variable `_big` and drops it -- so the swap belongs here, on
            # the value, which is where the ordinary store path does it too.
            # Without this, `already header (length is 4660)` stored 4660 raw
            # into a `2 bytes as big` field and read back 13330, while both
            # `h.length is 4660` and a template writing the same field were
            # correct. One construction form disagreeing with the other two.
            def _init_value(path, val):
                v = resolve_value(val, scalars, buffers, st["line"])
                _pl = (idefn.get("playout") or {}).get(path)
                if _pl is not None:
                    _off, _width, _sg, _big = _pl
                    if _big and _width > 1:
                        v = big_write(v, _width)
                return v

            assigns = [(state_cell(inst["name"], path, idefn, inst.get("backing")),
                        _init_value(path, val))
                       for path, val in inst["runinit"].items()]
            into.append({"adopt": True, "assigns": assigns,
                               "pname": None, "noreturn": False, "args": [],
                               "out": None, "clauses": [], "label": None,
                               "recover": None, "gtarget": None,
                               "resume": None})
            return

        if st["type"] == "construct" and st["name"] in buffers \
                and buffers[st["name"]].get("bitfields") \
                and is_pure_layout(definitions[buffers[st["name"]]["layout"]]):
            # `INST is FlagView` with no backing -- it owns its word, already
            # zeroed (every bit low), so there is nothing to construct. Any
            # Any arguments would be bit names, which are set with
            # `INST.FIELD is high` instead.
            for port, _actual, ln in st["conns"]:
                fail(f"line {ln}: set a flag view's bits with "
                     f"`{st['name']}.{port} is high`, not in the argument list")
            return

        if st["type"] == "construct" and st["name"] in buffers \
                and buffers[st["name"]].get("playout") \
                and is_pure_layout(definitions[buffers[st["name"]]["layout"]]):
            # `INST is LAYOUT where field is v ...` -- a pure layout (no
            # lifecycle): zeroed, so construction is a store per field. (Give
            # it `acquire`/`release` and it is a resource -> its acquire.)
            pl = buffers[st["name"]]["playout"]
            for port, actual, ln in st["conns"]:
                if port not in pl:
                    fail(f"line {ln}: layout '{st['name']}' has no field "
                         f"'{port}' (has: {', '.join(pl)})")
                off, width, _sg, big = pl[port]
                val = resolve_value(actual, scalars, buffers, ln)
                if big and width > 1:
                    val = big_write(val, width)
                into.append(
                    {"store_addr": f"((long){st['name']} + {off})",
                     "store_val": val,
                     "store_type": width_type(str(width), ln), "pname": None})
            return

        if st["type"] == "construct" and st["name"] in instances:
            _c = definitions[instances[st["name"]]["definition"]]
            _has = {m["role"] for m in _c["methods"].values()}
            if ("acquire" not in _has and "release" not in _has
                    and not _c.get("layers")):
                # no lifecycle: this is storage of that shape, already zeroed.
                # Any arguments are field values, set like an adoption.
                for port, actual, ln in st["conns"]:
                    if port not in _c.get("flat", {}):
                        fail(f"line {ln}: '{st['name']}' has no field '{port}'")
                    instances[st["name"]].setdefault("init", {})[port] = actual
                return

        if st["type"] == "construct":
            if st["recover"] is not None:
                fail(f"line {st['recover']['line']}: cannot `or continue` a "
                     "construction -- continuing without the resource needs "
                     "drop flags (not in v1)")
            inst = instances[st["name"]]
            defn = definitions[inst["definition"]]
            if defn.get("layers"):
                # LAYERED construct: run each layer's acquire base-first, each a
                # fallible step routing to the floor that releases the layers
                # already up. So an open-fault releases nothing; a snapshot-fault
                # closes the fd but SKIPS restore (its floor is the base layer's);
                # normal exit enters the top floor = restore then close.
                constructed.add(inst["name"])
                record_live(inst["name"])
                nm = inst["name"]
                below = f"release_{live[-2]}" if len(live) >= 2 else final["op"]
                consumed = set()
                for i, layer in enumerate(defn["layers"]):
                    init = layer["init"]
                    if init is None:
                        continue             # a layer that adds no acquire
                    lconns = [(p, a, ln) for (p, a, ln) in st["conns"]
                              if p in init["dirs"]]
                    consumed |= {p for p, _, _ in lconns}
                    vm = wire_call(init, defn, inst, lconns, scalars, buffers,
                                   st["line"])
                    _, largs, lout, lclauses = call_parts(init, vm)
                    ps = {"pname": init["prim"], "noreturn": False,
                          "args": largs, "out": lout, "clauses": lclauses,
                          "label": None, "recover": None, "gtarget": None,
                          "resume": None}
                    if lclauses:
                        if stage_slot is None:
                            fail(f"line {st['line']}: cannot derive the status "
                                 "slot -- wire a scalar into the final step")
                        tgt = below if i == 0 else f"release_{nm}__{i - 1}"
                        ps.update({"stage": len(fallible) + 1, "ref": nm,
                                   "ident": (None, nm), "target": tgt,
                                   "errsrc": lout if lout
                                   else vm[init["ensure"][0][0]],
                                   "strings": [a for _, a, _ in lconns
                                               if is_str(a)],
                                   "code": "1", "line": st["line"]})
                        fallible.append(ps)
                        ps["gtarget"] = error_label(ps["stage"], nm)
                    into.append(ps)
                extra = [p for p, _, _ in st["conns"] if p not in consumed]
                if extra:
                    fail(f"line {st['line']}: '{nm}' has no parameter "
                         f"'{extra[0]}' (no layer's acquire declares it)")
                return
            meth = defn["methods"]["acquire"]
            ident = (None, inst["name"])
            ref = inst["name"]
        else:
            inst, defn = callee(st["inst"], st["line"])
            meth = defn["methods"].get(st["method"])
            if meth is None:
                fail(f"line {st['line']}: {kind_of(defn)} '{defn['name']}' has no method "
                     f"'{st['method']}'")
            if meth["role"] == "acquire":
                fail(f"line {st['line']}: construct with "
                     f"`{st['inst']} is {defn['name']} where ...`, not a call")
            if meth["role"] == "release":
                fail(f"line {st['line']}: release is derived from ownership; "
                     "remove the step")
            if inst["mode"] == "owned" and inst["name"] not in constructed:
                fail(f"line {st['line']}: '{st['method']} {st['inst']}' used "
                     "before its construction")
            for lname in sorted(inst["lenders"]):
                lender = instances[lname]
                if (lender["mode"] == "owned"
                        and lname not in constructed):
                    fail(f"line {st['line']}: '{st['method']} {st['inst']}' "
                         f"uses '{lname}' before its construction")
            ident = (st["method"], st["inst"])
            ref = f"{st['method']} {st['inst']}"

        valmap = wire_call(meth, defn, inst, st["conns"], scalars, buffers,
                           st["line"])

        if st["type"] == "construct":
            constructed.add(inst["name"])
            record_live(inst["name"])

        prim, args, out, clauses = call_parts(meth, valmap)

        alts = []
        if st["alts"]:
            if not clauses:
                fail(f"line {st['alts'][0]['line']}: '{ref}' has no `ensure`; "
                     "alternatives are unreachable")
            base_binds = {p2: a for p2, a, _ in st["conns"]}
            for alt in st["alts"]:
                avm = wire_call(meth, defn, inst, alt["conns"], scalars,
                                buffers, alt["line"])
                abinds = {p2: a for p2, a, _ in alt["conns"]}
                for p2 in meth["params"]:
                    if (meth["dirs"][p2] != "value"
                            and abinds.get(p2) != base_binds.get(p2)):
                        fail(f"line {alt['line']}: an alternative may only "
                             f"vary value inputs -- '{p2}' must stay "
                             f"'{base_binds[p2]}' (got '{abinds[p2]}')")
                _, aargs, aout, aclauses = call_parts(meth, avm)
                alts.append({"pname": meth["prim"], "args": aargs,
                             "out": aout, "clauses": aclauses,
                             "strings": [a for _, a, _ in alt["conns"]
                                         if is_str(a)]})

        ps = {"pname": meth["prim"], "noreturn": False, "args": args,
              "out": out, "clauses": clauses, "label": None,
              "recover": None, "gtarget": None, "resume": None}
        rec = st["recover"]
        rid = None
        if alts or rec is not None:
            n_resume += 1
            rid = n_resume
            ps["resume"] = f"resume_{rid}"
        last_target = None
        if rec is not None:
            if not clauses:
                fail(f"line {rec['line']}: '{ref}' has no `ensure`; nothing "
                     "to recover from")
            if (prim["out"] and prim["out"] in meth["bind"]
                    and meth["bind"][prim["out"]][0] in defn["flat"]):
                fail(f"line {rec['line']}: '{meth['name']}' writes instance "
                     "state; repairs cannot reach it (not in v1)")
            bound_outs = {p2 for p2 in meth["params"]
                          if meth["dirs"][p2] == "return"}
            seen, assigns = set(), []
            for port, val, ln in rec["assigns"]:
                if port in seen:
                    fail(f"line {ln}: '{port}' repaired twice")
                seen.add(port)
                if port not in bound_outs:
                    fail(f"line {ln}: '{port}' is not an out of "
                         f"'{meth['name']}'")
                if not is_int(val):
                    fail(f"line {ln}: repair value '{val}' must be a plain "
                         "number -- `or continue` only substitutes a value "
                         "for the output, it does not read other slots")
                assigns.append((valmap[port], val))
            missing = sorted(bound_outs - seen)
            if missing:
                fail(f"line {rec['line']}: repair must cover every out "
                     f"(missing: {', '.join(missing)})")
            r = {"label": f"recover_{rid}", "resume": f"resume_{rid}",
                 "assigns": assigns}
            recovers.append(r)
            ps["recover"] = r
            last_target = r["label"]
        elif clauses:
            if stage_slot is None:
                fail(f"line {final['line']}: cannot derive the status slot -- "
                     "wire a scalar into the final noreturn step")
            # a failed construction routes by the live set BEFORE it (its own
            # instance, appended above, has nothing to release yet)
            floor = live[:-1] if st["type"] == "construct" else live
            last_target = error_label(len(fallible) + 1, ref)
            ps.update({
                "stage": len(fallible) + 1,
                "ref": ref,
                "ident": ident,
                "target": f"release_{floor[-1]}" if floor else final["op"],
                "errsrc": out if out else valmap[meth["ensure"][0][0]],
                "strings": ([a for _, a, _ in st["conns"] if is_str(a)]
                            + [s for a2 in alts for s in a2["strings"]]),
                "code": "1",
                "line": st["line"],
            })
            fallible.append(ps)
        if clauses:
            if alts:
                ps["gtarget"] = f"attempt_{rid}_2"
                for i, a in enumerate(alts):
                    a["label"] = f"attempt_{rid}_{i + 2}"
                    a["next"] = (f"attempt_{rid}_{i + 3}"
                                 if i + 1 < len(alts) else last_target)
                    a["resume"] = f"resume_{rid}"
                attempts.append(alts)
            else:
                ps["gtarget"] = last_target
        into.append(ps)

    for st in steps:
        plan_one(st, plan_steps)

    # failures-section overrides: named references, checked 1:1
    used_codes = {}
    for ov in overrides:
        if ov["code"] == "0":
            fail(f"line {ov['line']}: exit code 0 means success; overrides "
                 "must be nonzero")
        matches = [ps for ps in fallible
                   if ps["ident"] == (ov["method"], ov["inst"])]
        ref = (f"{ov['method']} {ov['inst']}" if ov["method"] else ov["inst"])
        if not matches:
            fail(f"line {ov['line']}: no fallible step '{ref}'")
        if len(matches) > 1:
            fail(f"line {ov['line']}: '{ref}' occurs {len(matches)} times; "
                 "the reference is ambiguous")
        ps = matches[0]
        if ps["code"] != "1":
            fail(f"line {ov['line']}: '{ref}' already has an override")
        if ov["code"] in used_codes:
            fail(f"line {ov['line']}: exit code {ov['code']} already used on "
                 f"line {used_codes[ov['code']]}")
        used_codes[ov["code"]] = ov["line"]
        ps["code"] = ov["code"]

    # a bare final step exits with the implicit status: the emitter's
    # variable when failures can store into it, the literal 0 otherwise
    if not final["conns"]:
        plan_steps[-1]["args"] = ["_status" if fallible else "0"]

    # the derived epilogue: a release tower, reverse acquisition order.
    # A floor runs the instance's whole cleanup chain (its own release,
    # then its parts', C++ destruction order -- propagated by elaboration)
    cascade = []

    def floor_calls_for(name, defn, cleanup):
        return [{"pname": cprim,
                 "args": [lit_c(a) if is_int(a) or is_str(a)
                          else state_cell(name, a, defn, instances[name].get("backing"))
                          for a in cargs]}
                for cprim, cargs in cleanup]

    for name in reversed(tower_order):
        defn = definitions[instances[name]["definition"]]
        if defn.get("layers"):
            # one floor per layer, top-first: `release_{name}` runs the top
            # layer then falls through to `release_{name}__i` for each lower
            # layer, the base floor chaining out to the enclosing scope. A
            # per-layer construct fault lands on the floor for the layers below
            # it (so a half-built stack unwinds exactly what it acquired).
            k = len(defn["layers"]) - 1
            for i in range(k, -1, -1):
                cascade.append({
                    "label": f"release_{name}" if i == k
                    else f"release_{name}__{i}",
                    "name": name,
                    "calls": floor_calls_for(name, defn, defn["layers"][i]["cleanup"]),
                    "chain": name if i > 0 else enclosing.get(name)})
        else:
            cascade.append({"label": f"release_{name}", "name": name,
                            "calls": floor_calls_for(name, defn, defn["cleanup"]),
                            "chain": enclosing.get(name)})

    # the outermost-scope resource still live at exit -- where normal exit
    # enters the tower (inner floors above it are for faults only).
    exit_top = live[-1] if live else None
    return (plan_steps, fallible, recovers, attempts, cascade,
            stage_slot, scalars, branch_colds, exit_top)


def buffer_size(tok, scalars):
    v = _int_value(tok)                       # a literal size (dec/hex/binary)
    return str(v) if v is not None else scalars[tok]["init"]


def scalar_reads(slots, steps):
    """Every name that could be a READ in this scope. Gathered GENEROUSLY: every
    identifier in any step or slot field counts EXCEPT an assignment's own target
    (and a loop label), so a genuinely-used scalar is never falsely flagged -- at
    worst a real typo slips through (a name that happens to match some port key)."""
    used = set()

    def grab(obj):
        if isinstance(obj, str):
            used.update(re.findall(r"[A-Za-z_]\w*", obj))
        elif isinstance(obj, dict):
            for v in obj.values():
                grab(v)
        elif isinstance(obj, (list, tuple)):
            for v in obj:
                grab(v)

    for st in steps:
        for k, v in st.items():
            if k == "name" and st.get("type") in NOT_A_READ:
                continue                      # a write target / a loop label
            grab(v)
    for sl in slots:
        if sl.get("kind") == "buffer":
            grab(sl.get("size"))              # a scalar-sized buffer reads it
        elif sl.get("kind") == "instance":
            grab(sl.get("init"))              # `field is SCALAR` at construction
            grab(sl.get("lens"))              # a view over a scalar reads it
            grab(sl.get("pending"))
            grab(sl.get("lens_off"))          # a name in a lens offset (rejected
                                              # later as a runtime offset) is a use
    return used


def dead_scalars(slots, used, bound=()):
    """The scalars in `slots` that nothing in `used` reads. `bound` names come
    from outside the scope (a template's parameters and the instance state it
    works on), so they are not its to declare or retire."""
    return [sl for sl in slots
            if sl.get("kind") == "scalar" and not sl["name"].startswith("_")
            and not sl.get("container")       # a container's length/count are
            and sl["name"] not in bound       # part of it, not standalone slots
            and sl["name"] not in used]


def check_scalar_use(slots, steps):
    """A top-level scalar that is written/declared but never READ is a leftover
    or -- now that a first `X is EXPR` declares X -- a mistyped assignment target
    that silently made a new slot. Flag it. Runs on the TOP-LEVEL program, before
    procedures inline; a scalar handed to a procedure shows up as that call's
    actual, so it counts. A TEMPLATE's own locals get the same check where they
    are parsed, in `inline_procedure`."""
    for sl in dead_scalars(slots, scalar_reads(slots, steps)):
        fail(f"line {sl['line']}: scalar '{sl['name']}' is assigned but "
             "never read -- remove it, or is the name a typo?")



def transpile(sources, prog):
    global CURRENT_FILE, PRIMITIVES, VIEWS
    INSTANCE_FIELDS.clear()
    REGISTER_WORDS.clear()
    SCALAR_WORDS.clear()
    definitions, slots, steps, overrides, prims = {}, [], [], [], {}
    flags = {}
    for fname, text in sources:
        CURRENT_FILE = fname
        flags["content"] = False
        parse(text, definitions, slots, steps, overrides, prims, flags)
    check_steps(steps)          # the parse produced only declared shapes
    check_scalar_use(slots, steps)
    CURRENT_FILE = None
    PRIMITIVES = prims
    VIEWS = flags.get("views", set())          # entry views this program declared
    (plan_steps, fallible, recovers, attempts, cascade,
     stage_slot, scalars, branch_colds, exit_top) = plan(definitions, slots, steps,
                                                         overrides)

    # a program that owns cleanup gets automatic interrupt handling: Ctrl-C /
    # SIGTERM turns the in-flight blocking syscall into an -EINTR fault, which
    # the existing tower then cleans up. Nothing to release -> nothing to guard,
    # so the stub is omitted and the default disposition (terminate) stands.
    interrupts_on = bool(cascade)
    # any program doing checked I/O can hit a broken pipe (a reader that went
    # away mid-write); SIGPIPE's default action is to KILL, past the tower, so we
    # ignore it -- the write then faults -EPIPE, routed like any other fault.
    # Broader than the interrupt stub: no cleanup needed, just a writer.
    sigpipe_on = bool(fallible)

    # every emitted call, across the happy path, alternatives, and the
    # cleanup tower, so the right wrappers are emitted (and no others)
    # The cold `when` roads count too: a call that appears ONLY in one still
    # needs its wrapper. It went unnoticed while a road could hold nothing but a
    # fallible call (those reach `fallible`, and through it the same scan) --
    # the moment a road could hold a whole spliced body, an infallible call in
    # one compiled to an undeclared `_assembly_open`.
    emitted = [d for d in (plan_steps + [a for alts in attempts for a in alts]
                           + [c for f in cascade for c in f["calls"]]
                           + [ps for cold in branch_colds for road in cold
                              for ps in road["plan"]]
                           + [c for cold in branch_colds for road in cold
                              for ps in road["plan"]
                              for c in (ps.get("scope_release") or [])
                              + (ps.get("releases") or [])])
               if d.get("pname")]
    used = {d["pname"] for d in emitted}
    # the transpiler's own two syscalls, emitted as raw inline asm (no generic
    # syscallN wrapper): write for the stderr records + _write_value, and
    # rt_sigaction for the signal dispositions
    out = []
    if fallible:
        out.append(SYS_WRITE)
    if sigpipe_on or interrupts_on:
        out.append(SYS_SIGACTION)
    out += [emit_asm_wrapper(p, PRIMITIVES[p]) for p in sorted(used)
            if PRIMITIVES[p].get("kind") == "asm"]
    out += [HELPER_C[c] for c in sorted(                    # the byte-layer helpers
            {PRIMITIVES[p]["cfunc"] for p in used
             if PRIMITIVES[p].get("kind") == "helper"})]
    if interrupts_on:
        out.append(SIGSTUB)
    if fallible:
        out.append(WRITE_VALUE)
    if {"environment", "auxiliary"} & VIEWS:
        out.append(VECLEN)                    # envp/auxv are NULL-terminated
    if "auxiliary" in VIEWS:
        out.append(AUXLEN)

    # The kernel enters _start with rsp 16-byte aligned; GCC compiles _start as
    # an ordinary function, which assumes the post-`call` alignment (rsp%16==8)
    # -- off by 8. Any aligned SSE store to a local (a constant array init lowers
    # to `movaps`) then faults with #GP. force_align_arg_pointer realigns the
    # stack in the prologue, making _start a correct freestanding entry.
    #
    # If the program declared entry views (`program with ... is`), _start is a
    # naked stub that captures the entry rsp -- the kernel points it at
    # [argc, argv…, NULL, envp…, NULL, auxv…] -- BEFORE the realign prologue can
    # move it, then tail-jumps (no call/ret) into the aligned body `_run`.
    #
    # externally_visible: the build compiles with -fwhole-program, which makes
    # every non-`extern` function static -- and a static function nothing calls
    # is dead code. `_start` is called by the KERNEL and `_run` is reached from
    # `_start`'s inline asm, neither of which GCC can see, so without this both
    # are deleted and the binary has no entry symbol at all.
    if VIEWS:
        body = ["void _run(long _entry);",
                "",
                "__attribute__((naked, externally_visible)) void _start(void) {",
                "    __asm__(",
                '        "mov %rsp, %rdi\\n"       /* entry pointer (-> argc) */',
                '        "jmp _run\\n"',
                "    );",
                "}",
                "",
                "__attribute__((force_align_arg_pointer, externally_visible))",
                "void _run(long _entry) {"]
    else:
        body = ["__attribute__((force_align_arg_pointer, externally_visible))",
                "void _start() {"]
    # The signal dispositions go in FIRST, ahead of every declaration. They read
    # nothing a declaration writes -- `_sigign`/`_sigact` are their own locals --
    # but `_sigaction` is inline asm with a "memory" clobber, so anything
    # initialized ABOVE it is memory the syscall might read, and GCC must keep
    # the stores. A pure layout's `= {0}` is exactly such a store, and it is
    # usually dead (the fields get written before anything reads them). Emitted
    # above the clobber it survived to the binary: `data is structure` cost 14
    # bytes more than the identical `buffer is 24 bytes` + `buffer as structure`.
    # Below it, GCC folds the dead zeroing away and the two forms are
    # byte-identical -- same zero-filled semantics, no instructions.
    body.extend(signal_prologue(sigpipe_on, interrupts_on))
    bufnames = {s["name"] for s in slots if s["kind"] == "buffer"
                or (s["kind"] == "instance"
                    and definitions[s["definition"]].get("playout")
                    and is_pure_layout(definitions[s["definition"]]))}
    for slot in slots:
        if slot["kind"] == "buffer" and slot.get("place") == "register":
            # `in register`: ONE word, no array, nothing to take the address of.
            # Every slice of it is shift-and-mask on this variable.
            body.append(f"    unsigned long {slot['name']} = 0;")
        elif slot["kind"] == "buffer":
            al = (f" __attribute__((aligned({slot['align']})))"
                  if slot.get("align") else "")
            if "init" in slot:
                init = ", ".join(str(b) for b in slot["init"])
                # `constant` -> read-only static storage (.rodata): no runtime
                # copy, and it links where a large stack initializer would not
                ro = "static const " if slot.get("const") else ""
                body.append(f"    {ro}unsigned char {slot['name']}"
                            f"[{len(slot['init'])}]{al} = {{{init}}};")
            else:
                sc = "static " if slot.get("place") == "static" else ""
                body.append(f"    {sc}char {slot['name']}"
                            f"[{buffer_size(slot['size'], scalars)}]{al};")
        elif slot["kind"] == "scalar":
            body.append(f"    long {slot['name']} = {slot['init']};")
        elif slot.get("lens"):
            pass                          # a lens owns no storage -- it IS its backing
        elif (slot["kind"] == "instance"
              and definitions[slot["definition"]].get("playout")
              and is_pure_layout(definitions[slot["definition"]])):
            # a PURE LAYOUT: a scoped, zero-initialized stack block (addressable;
            # each instance its own). Only a lifecycle makes it a resource ->
            # the scalar-long path below (register-resident). An
            # `aligned M` on the instance sets the block's alignment (SIMD, DMA).
            al = (f" __attribute__((aligned({slot['align']})))"
                  if slot.get("align") else "")
            body.append(f"    char {slot['name']}"
                        f"[{definitions[slot['definition']]['psize']}]{al} = {{0}};")
        elif (slot["kind"] == "instance"
              and definitions[slot["definition"]].get("bitfields") is not None
              and is_pure_layout(definitions[slot["definition"]])):
            # a `new` FLAG VIEW owns its word: a zeroed backing (all bits low)
            body.append(f"    char {slot['name']}"
                        f"[{definitions[slot['definition']]['bitwidth']}] = {{0}};")
        else:
            defn = definitions[slot["definition"]]
            const = slot.get("constinit", {})
            for path, default in defn["flat"].items():
                if path in defn.get("arrays", ()):
                    # a resource's in-instance buffer: a zeroed char array, its
                    # name IS its address (state_cell hands out `(long)NAME`)
                    body.append(f"    char {slot['name']}_"
                                f"{path.replace(' ', '_')}"
                                f"[{defn['playout'][path][1]}] = {{0}};")
                    continue
                # constant adopted values are top-declared; runtime ones
                # (scalar slots) default here and are set at the adopt step
                if path in const:
                    v = const[path]
                    if v in bufnames:        # a buffer name is its address
                        init = f"(long){v}"
                    else:
                        init = lit_c(v)
                else:
                    init = default
                # A field declared `N bytes` keeps that width even here, where
                # the state is a register word rather than memory -- the same
                # rule a view `in register` follows, so one declaration means one
                # thing in both. A field declared scalar-style (`address is 0`)
                # has no width to keep and stays a full word.
                _pl = (defn.get("playout") or {}).get(path)
                _ct = width_type(str(_pl[1]), slot["line"], _pl[2]) if _pl else "long"
                body.append(f"    {_ct} {slot['name']}_"
                            f"{path.replace(' ', '_')} = {init};")
    if fallible and stage_slot == "_status":
        body.append("    long _status = 0;")
    if "_sink" in scalars:
        body.append("    long _sink = 0;")   # discarded out-ports land here

    if VIEWS:
        # derive the requested views from the captured entry pointer. The regions
        # are sequential on the stack, so envp needs argc and auxv needs both --
        # the chain is computed as far as the deepest requested view.
        body.append("")
        body.append("    long _argc = *(long *)_entry;")
        body.append("    char **_argv = (char **)(_entry + 8);")
        if {"environment", "auxiliary"} & VIEWS:
            body.append("    char **_envp = _argv + _argc + 1;")
            body.append("    long _envc = _veclen(_envp);")
        if "auxiliary" in VIEWS:
            body.append("    long *_auxv = (long *)(_envp + _envc + 1);")
            body.append("    long _auxc = _auxlen(_auxv);")

    def emit_step(p, body):
        """Emit ONE planned step. Shared by the spine and by the cold `when`
        road blocks, because a road holds whatever the spine holds. The road
        emitter used to know six of these kinds; the first store or `ensure`
        spliced into a road fell through to `render_call` with no primitive
        and crashed. The noreturn/tower case simply never fires in a road."""
        if p.get("assign"):                      # `X is EXPR` -- recompute
            body.append(f"    {p['assign']} = {p['expr_c']};")
            return
        # a store may carry `when COND` -- the guard wraps whichever single
        # statement it became. Absent everywhere else, so this costs nothing.
        guard = f"if ({p['when_c']}) " if p.get("when_c") else ""
        if p.get("stmt") is not None:            # a raw statement: a void atomic
            body.append(f"    {guard}{p['stmt']};")  # op/fence, or a register
            return                                   # word's masked write
        if p.get("store_addr") is not None:      # `[ADDR : N] is VALUE` -- store
            t = p["store_type"]
            body.append(f"    {guard}*({t} *)({deref_addr(p['store_addr'])}) = "
                        f"({t})({p['store_val']});")
            return
        if p.get("store_bits") is not None:      # `BIT of view is VALUE` -- a
            cell, ut, lo, mask, val, cast = p["store_bits"]   # masked RMW
            # the suffix follows the cell: a register word shifts past bit 31,
            # where a plain `u` literal would overflow. `cast` brings the result
            # back to a signed scalar's own type. (GCC folds high/low to
            # or/andnot either way.)
            sfx = "ul" if ut == "unsigned long" else "u"
            bits = cell if not cast else f"(unsigned long){cell}"
            rhs = (f"({bits} & ~({mask}{sfx} << {lo})) "
                   f"| ((({val}) & {mask}{sfx}) << {lo})")
            body.append(f"    {guard}{cell} = "
                        f"{f'({cast})({rhs})' if cast else rhs};")
            return
        if p.get("scope_guard"):                 # `GUARD goes` -- the entry test
            body.append(f"    if (!({p['scope_guard']})) goto {p['skip']};")
            return
        if p.get("scope_release") is not None:   # a scope's end -- release what
            for c in p["scope_release"]:          # it holds, reverse order
                body.append(f"    {render_call(c)};")
            if p.get("exit_label"):               # where a `leave NAME` lands
                body.append(f"{p['exit_label']}:")
            return
        if "loop_top" in p:                      # a scope's start label -- present
            if p["loop_top"]:                    # only when something repeats
                body.append(f"{p['loop_top']}:") # back to it
            return
        if p.get("loop_exit"):                   # `leave NAME` -- out of the loop
            # the same releases `again` does, then a jump past the back-edge.
            # Under a `when`, both go inside the guard: not leaving must not
            # release anything.
            if p.get("cond_c"):
                if p["releases"]:
                    body.append(f"    if ({p['cond_c']}) {{")
                    for c in p["releases"]:
                        body.append(f"        {render_call(c)};")
                    body.append(f"        goto {p['loop_exit']};")
                    body.append("    }")
                else:
                    body.append(f"    if ({p['cond_c']}) "
                                f"goto {p['loop_exit']};")
            else:
                for c in p["releases"]:
                    body.append(f"    {render_call(c)};")
                body.append(f"    goto {p['loop_exit']};")
            return
        if p.get("loop_back"):                   # `again` -- end of iteration
            for c in p["releases"]:              # release body-acquired first
                body.append(f"    {render_call(c)};")
            if p.get("cond_c"):                  # `again when COND` -- bounded
                body.append(f"    if ({p['cond_c']}) goto {p['loop_back']};")
            else:                                # bare `again` -- forever
                body.append(f"    goto {p['loop_back']};")
            if p.get("exit_label"):              # where every `leave` lands
                body.append(f"{p['exit_label']}:")
            return
        if p.get("adopt"):                       # take ownership of an fd
            for tgt, rhs in p["assigns"]:
                body.append(f"    {tgt} = {rhs};")
            return
        if p.get("branch_dispatch") is not None:  # peel cold `when` roads off
            # `likely` is a statement: every `when` edge is expect-cold, so the
            # compiler neither lays a road hot NOR speculates its selection
            # onto the spine (assign-only roads are cheap enough to tempt it)
            for g in p["branch_dispatch"]:
                body.append(f"    if (__builtin_expect({g['pred']}, 0)) "
                            f"goto {g['label']};")
            return
        if p.get("branch_merge"):                 # roads rejoin the spine here
            body.append(f"{p['branch_merge']}:")
            return
        if p.get("pname") is None and p.get("stage") is not None:
            for pred in p["clauses"]:            # `ensure` guard: check, no call
                body.append(f"    if (__builtin_expect(!({pred}), 0)) "
                            f"goto {p['gtarget']};")
            return
        call = render_call(p)
        stmt = f"{p['out']} = {call};" if p["out"] else f"{call};"
        if p["label"]:                       # the final noreturn step: floor 0
            # normal exit enters at the outermost-scope top; if inner-scope
            # floors sit above it (loop/block/method resources already released
            # at their own scope exit), jump past them -- they stay for faults.
            if cascade and (not exit_top or exit_top != cascade[0]["name"]):
                body.append(f"    goto release_{exit_top};" if exit_top
                            else f"    goto {p['label']};")
            for i, f in enumerate(cascade):
                body.append(f"{f['label']}:")
                for c in f["calls"]:
                    body.append(f"    {render_call(c)};")
                # fall through to the next floor only if it IS this one's
                # enclosing scope; otherwise jump to the enclosing floor (or
                # exit) -- so a dead inner floor between us and it is skipped
                nxt = cascade[i + 1]["name"] if i + 1 < len(cascade) else None
                if f["chain"] != nxt:
                    body.append(f"    goto release_{f['chain']};" if f["chain"]
                                else f"    goto {p['label']};")
            body.append(f"{p['label']}:")
        body.append(f"    {stmt}")
        if p["noreturn"]:
            body.append("    __builtin_unreachable();")
        for pred in p["clauses"]:
            body.append(f"    if (__builtin_expect(!({pred}), 0)) "
                        f"goto {p['gtarget']};")
        if p["resume"]:
            body.append(f"{p['resume']}:")

    # `repeat program` lands here: past the entry views and the signal
    # dispositions, at the first step. Emitted only when something jumps to it,
    # so a program that does not repeat is unchanged.
    if any(p.get("loop_exit") == PROGRAM_AGAIN
           for p in plan_steps + [ps for cold in branch_colds for road in cold
                                  for ps in road["plan"]]):
        body.append("")
        body.append(f"{PROGRAM_AGAIN}:;")

    for p in plan_steps:
        if p.get("adopt") and not p["assigns"]:
            continue                             # empty view -> top-declared
        if "loop_top" in p and not p["loop_top"]:
            continue                             # a scope nothing repeats to
        body.append("")
        emit_step(p, body)

    # cold `when` roads FIRST among the cold blocks: they are normal control
    # flow, only less likely, so they sit closest to the hot path -- ahead of
    # every error-handling block (retries, records, recovery), which trail as
    # the last thing in the layout. Each road runs its steps and jumps back to
    # the merge; the `likely` default road already sits inline on the spine.
    for cold in branch_colds:
        for road in cold:
            body.append("")
            if road.get("nested"):        # read by mereocheck: this crossroad's
                body.append(              # dispatch is itself in the cold tail
                    f"    /* nested: {road['label']} */")
            body.append(f"{road['label']}:")
            for ps in road["plan"]:
                if ps.get("adopt") and not ps["assigns"]:
                    continue                     # empty view -> top-declared
                if "loop_top" in ps and not ps["loop_top"]:
                    continue                     # a scope nothing repeats to
                emit_step(ps, body)
            # An ASSIGN-ONLY road is pure movs -- cheap enough that the
            # optimizer would speculate it onto the spine or if-convert it
            # into cmovs, putting a cold road's work on the hot path. The
            # pinned asm (zero instructions) anchors the values in the block:
            # the road stays a road, entered only by its guard.
            #
            # Only assign-only, and the wording was always the intent -- the
            # test was not. A road holding a spliced template holds calls,
            # stores and loops, which nothing if-converts, so the pin buys
            # nothing there; and its operand list grew with every local the
            # splice brought until GCC refused it ("more than 30 operands in
            # asm"). Each name is pinned once for the same reason.
            #
            # A NESTED CROSSROAD is neutral here: its dispatch and merge are
            # control flow, not work, so a road that only selects -- even when
            # the selecting is done by a spliced crossroad -- is still pure movs
            # and still needs the pin. Reading those two markers as "not an
            # assign" is what let GCC hoist a cold road's constant stores into
            # the middle of the spine, which the build gate then caught.
            def _selects(ps):
                """A plan step that is pure SELECTION or a pure marker: a move,
                or something that emits no instruction at all. A splice brings
                its own scope markers (`loop_top` with nothing jumping to it,
                an empty `scope_release`) and a nested crossroad brings a
                dispatch and a merge -- all control flow, none of it work."""
                if ps.get("assign"):
                    return True
                if ps.get("adopt") and not ps["assigns"]:
                    return True
                if ps.get("branch_dispatch") or ps.get("branch_merge"):
                    return True
                if "loop_top" in ps and not ps["loop_top"]:
                    return True
                if "scope_release" in ps and not ps["scope_release"]:
                    return True
                return False
            leafy = all(_selects(ps) for ps in road["plan"])
            pins = list(dict.fromkeys(ps["assign"] for ps in road["plan"]
                                      if ps.get("assign"))) if leafy else []
            if pins:
                ops = ", ".join(f'"+r"({p2})' for p2 in pins)
                body.append(f'    __asm__("# {road["label"]}" : {ops});')
            body.append(f"    goto {road['back']};")

    # alternative attempts: cold retries of their step with new `in`
    # bindings; each jumps back to the step's resume label on success and
    # chains to the next attempt (finally the error/recover block) on
    # failure. The pinned asm keeps identical attempts (bounded retries)
    # from tail-merging into one another.
    for alts in attempts:
        for a in alts:
            body.append("")
            body.append(f"{a['label']}:")
            acall = render_call(a)
            body.append(f"    {a['out']} = {acall};" if a["out"]
                        else f"    {acall};")
            for pred in a["clauses"]:
                body.append(f"    if (__builtin_expect(!({pred}), 0)) "
                            f"goto {a['next']};")
            if a["out"]:
                body.append(f'    __asm__("# {a["label"]}" '
                            f': "+r"({a["out"]}));')
            body.append(f"    goto {a['resume']};")

    # cold stage blocks, past the noreturn tail: emit the one stderr record
    # (static prefix + errno name via one indexed load -- no itoa, no loop),
    # store the exit status (boolean 1 unless overridden), enter the tower.
    # The record writes are volatile asm, so the optimizer can neither hoist
    # these blocks nor if-convert the guards: the happy path never touches
    # the status slot (its declared init is the success value).
    for p in fallible:
        # the record prefix is fully static: program, stage, step reference,
        # and every string literal bound at this step (a failed open names
        # its path at zero runtime cost)
        strs = "".join(f" {tok}" for tok in p["strings"])
        text = f"{prog}: {p['stage']}: {p['ref']}{strs}: "
        esc = text.replace("\\", "\\\\").replace('"', '\\"')
        body.append("")
        body.append(f"{error_label(p['stage'], p['ref'])}:")
        # some faults are shutdown requests, not failures: a syscall cut short by
        # Ctrl-C/SIGTERM (-EINTR), or a write to a reader that finished early
        # (-EPIPE). Skip the record and the status store (status keeps its
        # success value) and drop to the same tower floor -- graceful, exit 0.
        # Cold, so the happy path pays nothing.
        graceful = ([("-4", "EINTR")] if interrupts_on else []) + \
                   ([("-32", "EPIPE")] if sigpipe_on else [])
        if graceful:
            cond = " || ".join(f"{p['errsrc']} == {v}" for v, _ in graceful)
            names = "/".join(n for _, n in graceful)
            body.append(f"    if ({cond}) goto {p['target']};"
                        f"   /* -{names}: graceful shutdown */")
        body.append(f'    _write(2, (long)"{esc}", {len(text.encode())});')
        body.append(f"    _write_value({p['errsrc']});")
        body.append(f"    {stage_slot} = {p['code']};")
        # the unique asm keeps this block a self-contained unit in the
        # binary: GCC fuses the identical tails of same-floor blocks (one
        # block jumping into the middle of another), and neither
        # -fno-crossjumping nor -fno-tree-tail-merge stops the last
        # two-insn merge -- a distinct asm template poisons every suffix
        # containing it, and the "+r" pin stops the scheduler floating it
        # above the store. Emits zero instructions (an assembler comment).
        body.append(f'    __asm__("# stage {p["stage"]}" : "+r"({stage_slot}));')
        body.append(f"    goto {p['target']};")

    # recovery blocks: repair the outs, rejoin the step's resume label.
    # Cold like the error blocks, but no record, no status store, and no
    # barrier -- each block ends in a goto to its OWN resume label, so no
    # two tails are identical and tail-merging has nothing to fuse.
    for r in recovers:
        body.append("")
        body.append(f"{r['label']}:")
        for tgt, val in r["assigns"]:
            body.append(f"    {tgt} = {val};")
        body.append(f"    goto {r['resume']};")
    body.append("}")

    out.append("\n".join(body))
    return "\n\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: mereoc.py <program.mereo>  (files declare their "
                 "imports with `use`; extra files before the program are "
                 "allowed as a low-level override)")
    prog = sys.argv[-1].rsplit("/", 1)[-1]
    prog = prog[:-6] if prog.endswith(".mereo") else prog
    sources, loaded = [], set()
    for path in sys.argv[1:]:
        sources += load(path, loaded, [])
    sys.stdout.write(transpile(sources, prog))

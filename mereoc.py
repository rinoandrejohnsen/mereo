#!/usr/bin/env python3
"""mereoc -- a literal .mereo -> freestanding C transpiler.

THE LANGUAGE IS DOCUMENTED IN docs/ -- start at docs/index.md, or read it
as one page (docs/mereo.html, regenerated by docs/build.py). That is the
spec, and every example in it is compiled and run. This docstring used to
carry a syntax summary as well; it drifted out of date (it documented port
direction verbs that were never implemented, and "limits" the language had
long since passed), so it now covers only what docs/ does not: the
contracts this transpiler guarantees about the C it emits, which the other
tools (mereocheck, mereodis, mereoraii) depend on.

CONTRACTS. A syscall declares what "it worked" means where the syscall
itself is declared -- `ensure PORT CMP VALUE` in its `assembly` block --
so the check sits as close to the failure as the language can put it. A
method that binds that port inherits the contract and needs no `ensure`
of its own. Writing one REPLACES the inherited check rather than adding
to it: the method has taken responsibility, and `write`'s `written ==
count` therefore still costs a single compare on the hot path instead of
two. A `release` never inherits (a failed release cannot reroute), and a
primitive with no `out` port -- or one with no -errno convention, like a
C helper or `popcnt` -- declares nothing.

FAILURE INTERFACE (derived). Exit status is BOOLEAN and IMPLICIT by
default: 0 = success, 1 = failure (or the override code), carried in an
emitter-owned variable no program text mentions. All detail goes to
stderr as ONE record, emitted in the cold block of the failing step:

    <program>: <stage>: <step> ["<strings>"...]: <value>\\n

program = the .mereo file's basename; stage = the fallible step's ordinal
(1..N, static text); step = the step reference (e.g. `read file`); any
string literals bound at the failing step are embedded statically, so a
failed open names the path it could not open. value = the RAW signed
result that violated the contract: negative is -errno (a missing file
prints -2), positive is the offending value itself (a short write prints
the byte count) -- the sign disambiguates. The conversion is straight-line
bounded decimal in the cold block (one `if` per digit, no itoa loop, no
tables); everything else is compile-time text. At most one record per
run, by construction. Parse it by splitting on `: ` from the RIGHT -- the
value is always the last field (paths may contain colons).

ROUTING AND CLEANUP are derived as before: the epilogue is a release
tower (release per live owned instance, reverse acquisition order,
falling through to `exit`); every ensure violation jumps to its cold
stage block (record, status store, then the tower at the floor matching
the live set at that step); a failed construction routes by the live set
before it. Cold blocks sit past the noreturn tail and now contain
syscalls, so the optimizer cannot hoist or if-convert them -- the happy
path never touches the status slot (its init is the success value) and
carries no failure logic at any -O level.

LAYERS. A resource owns exactly ONE acquirable thing -- but `acquire` may
take SEVERAL steps to get it into a usable state (open then bind then
setsockopt), and `release` may take several to let it go (unmap then
close). What is fixed is the count of things owned, not the count of
calls. In a multi-step `acquire` exactly one call carries `acquired when
COND`: that test IS the ownership boundary, so a fault BEFORE it releases
nothing and a fault AFTER it releases the one thing. Each acquire call
becomes its own layer, and the resource's cleanup rides on the marked one,
so the existing per-layer floors give the mid-sequence transition for
free. A single-call acquire needs no marker (the boundary is
unambiguous). `release` carries no test at any step -- a failed release
cannot reroute. Several things
are owned by LAYERING with `extends`, which takes any number of bases
(`extends A and B and C`). The layer list is built base-first: each base
contributes its own layers in the order written, then the resource's own
lifecycle if it has one -- so one extending several bases is layered
even when it declares nothing itself. Construction runs the acquires in
that order, each its own fallible step, and the tower gives every layer
its own FLOOR: a failure at layer k releases layers k-1..1 in reverse and
runs no release for k, which never acquired. That is what keeps
acquisition depth a COMPILE-TIME constant -- one acquire per layer -- and
so needs no drop flag and no unwinder. Each layer's acquire parameters
are bound BY NAME out of the single argument list; two layers naming a
parameter alike is therefore rejected at elaboration, since the shared
name would quietly wire two unrelated acquires to one value.

The transpiler knows only the primitive table (target-ABI mechanism).
Everything lowers into one flat `_start`: no functions (always_inline
wrappers), no unwinder, no drop flags -- so there is no recursion and no
dynamic dispatch. A method is either ONE primitive call (with `ensure`
postconditions) or a `procedure` body that is spliced at each call site.
"""


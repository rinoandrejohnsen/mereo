        'static inline __attribute__((always_inline)) long _decimal(long _n, long _op) {\n'
        '    char *_o = (char *)_op;\n'
        '    char _t[20];\n'
        '    long _i = 0, _j = 0;\n'
        '    if (_n < 0) { _o[_j++] = (char)45; _n = -_n; }\n'
        '    if (_n == 0) { _o[_j++] = (char)48; return _j; }\n'
        '    while (_n > 0) { _t[_i++] = (char)(48 + _n % 10); _n /= 10; }\n'
